"""Generate Error pathway wheel glyphs and simple model geometry. Run with Pillow installed."""
from pathlib import Path
import json
import math
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[3]
ASSETS = ROOT / 'src/main/resources/assets/circle_of_inevitability'
ICONS = ASSETS / 'textures/gui/ability_menus/worm_of_time'
MODELS = ASSETS / 'models/model_fx/worm_of_time'
TEXTURES = ASSETS / 'textures/model_fx/worm_of_time'
for path in (ICONS, MODELS, TEXTURES):
    path.mkdir(parents=True, exist_ok=True)

names = ['swindle','intent','dream','deceive','attack','swarm','avatar','recall','fate','exchange',
         'loophole','aging','slow','stop','haste','rewind','history','error','misdirect','succession']
S = 4
for name in names:
    im = Image.new('RGBA', (32*S,32*S))
    d = ImageDraw.Draw(im)
    def box(v): return tuple(round(x*S) for x in v)
    def line(points, fill=(194,255,244,255), width=1):
        d.line([(round(x*S),round(y*S)) for x,y in points],fill=fill,width=width*S,joint='curve')
    def circle(b,fill=None,outline=(87,205,191,255),width=1):
        d.ellipse(box(b),fill=fill,outline=outline,width=width*S)
    d.rounded_rectangle(box((1,1,31,31)),radius=7*S,fill=(9,18,25,245),outline=(51,104,109,255),width=S)
    if name in ('aging','slow','stop','haste','rewind','history'):
        circle((7,7,25,25))
        for i in range(12):
            a=i*math.tau/12
            line([(16+7*math.cos(a),16+7*math.sin(a)),(16+8.3*math.cos(a),16+8.3*math.sin(a))],width=1)
        line([(16,10),(16,16),(21,18)])
        if name=='stop':
            d.rectangle(box((12,12,14,21)),fill=(234,255,251,255));d.rectangle(box((18,12,20,21)),fill=(234,255,251,255))
        elif name=='rewind': line([(10,12),(6,16),(10,20)]);line([(6,16),(15,16)])
        elif name=='haste': line([(12,12),(17,16),(12,20)]);line([(18,12),(23,16),(18,20)])
        elif name=='aging': line([(12,10),(21,10),(13,22),(21,22)])
        elif name=='history': line([(10,12),(22,12),(22,21),(10,21),(10,12)])
        else: line([(10,26),(22,26)])
    elif name in ('avatar','succession','recall'):
        circle((12,6,20,14));line([(10,25),(10,20),(13,16),(19,16),(22,20),(22,25),(10,25)])
        circle((17,9,20,12),outline=(255,235,166,255))
        if name=='recall': line([(8,8),(5,12),(8,16)])
        if name=='succession': line([(9,5),(12,3),(16,5),(20,3),(23,5)])
    elif name=='dream':
        circle((8,7,25,24),fill=(126,235,222,255));circle((14,5,28,19),fill=(9,18,25,255),outline=None)
        line([(11,25),(21,25)])
    elif name=='swarm':
        for k in range(3):
            line([(8,10+6*k),(12,7+6*k),(16,10+6*k),(20,7+6*k),(24,10+6*k)],width=2)
    elif name in ('fate','exchange','misdirect'):
        line([(7,10),(19,10),(24,15),(19,20),(7,20)]);line([(19,6),(24,10),(19,14)])
        if name=='exchange': line([(12,16),(7,20),(12,24)])
        elif name=='fate': circle((12,12,19,19),outline=(255,235,166,255))
        else: line([(9,6),(15,14),(9,25)])
    elif name in ('error','loophole'):
        circle((7,7,25,25));d.rectangle(box((18,6,27,14)),fill=(9,18,25,255));line([(18,10),(24,10),(24,16)])
        if name=='error': line([(10,11),(20,21)]);line([(12,21),(22,11)])
    elif name in ('intent','deceive','swindle'):
        line([(6,16),(12,10),(20,10),(26,16),(20,22),(12,22),(6,16)]);circle((12,12,20,20))
        if name=='deceive': line([(7,25),(25,7)])
        elif name=='intent': line([(16,8),(16,24)],fill=(255,235,166,255))
        else: circle((16,11,25,20),outline=(255,235,166,255))
    elif name=='attack':
        line([(9,24),(23,7)],width=2);line([(7,17),(15,24)]);line([(20,7),(25,6),(24,11)])
    im.resize((32,32),Image.Resampling.LANCZOS).save(ICONS/f'{name}.png')

Image.new('RGBA',(16,16),(235,248,245,255)).save(TEXTURES/'pale.png')
Image.new('RGBA',(16,16),(35,44,50,255)).save(TEXTURES/'dark.png')

def cube(name,lo,hi,texture='pale'):
    return {'name':name,'from':lo,'to':hi,'shade':False,'faces':{
        face:{'uv':[0,0,16,16],'texture':'#'+texture} for face in ('north','south','east','west','up','down')}}
def save(name,elements):
    (MODELS/f'{name}.json').write_text(json.dumps({'credit':'Circle Of Inevitability: Error pathway; generated by tools/model_gen/worm_of_time/generate.py',
        'textures':{'pale':'circle_of_inevitability:model_fx/worm_of_time/pale','dark':'circle_of_inevitability:model_fx/worm_of_time/dark','particle':'circle_of_inevitability:model_fx/worm_of_time/pale'},
        'elements':elements},indent=2)+'\n')
clock=[]
for i in range(24):
    a=i*math.tau/24
    x,y=8+7*math.sin(a),8+7*math.cos(a)
    clock.append(cube(f'stone_{i}',[round(x-.6,3),round(y-.6,3),7.5],[round(x+.6,3),round(y+.6,3),8.5],'dark'))
for i in range(12):
    a=i*math.tau/12
    x,y=8+5.7*math.sin(a),8+5.7*math.cos(a)
    clock.append(cube(f'hour_{i}',[round(x-.25,3),round(y-.5,3),7.2],[round(x+.25,3),round(y+.5,3),7.5]))
save('ancient_clock',clock)
hand=[cube('minute',[7.82,8,7],[8.18,13,7.3]),cube('hour',[7.75,6,7],[8.25,8,7.3]),cube('pivot',[7.5,7.5,6.8],[8.5,8.5,7.5])]
save('clock_hand',hand)
avatar=[cube('coat',[4,9,6],[12,23,10],'dark'),cube('head',[5,23,5],[11,29,11],'dark'),
        cube('left_leg',[4.5,0,6.5],[7.5,9,9.5],'dark'),cube('right_leg',[8.5,0,6.5],[11.5,9,9.5],'dark'),
        cube('left_arm',[1,10,6.5],[4,23,9.5],'dark'),cube('right_arm',[12,10,6.5],[15,23,9.5],'dark'),
        cube('collar',[6.5,20,5.8],[9.5,23,6]),cube('monocle_top',[8.5,26,4.7],[10.5,26.3,5]),
        cube('monocle_bottom',[8.5,24.5,4.7],[10.5,24.8,5]),cube('monocle_left',[8.5,24.5,4.7],[8.8,26.3,5]),
        cube('monocle_right',[10.2,24.5,4.7],[10.5,26.3,5])]
save('avatar',avatar)
print(f'Generated {len(names)} icons and 3 models.')
