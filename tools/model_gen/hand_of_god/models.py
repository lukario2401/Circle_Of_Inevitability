def _rays(d, c, r0, r1, count, fill, width=1, phase=0.0, long_every=0, r_long=None):
    for i in range(count):
        a = math.tau * i / count + phase
        r_end = r_long if long_every and i % long_every == 0 else r1
        d.line([(c + math.cos(a) * r0, c + math.sin(a) * r0), (c + math.cos(a) * r_end, c + math.sin(a) * r_end)],
               fill=fill, width=width)


def _glyphs(d, c, radius, count, fill, seed, size=4):
    """Small angular runes round a circle (the Demon Hunter's and the Guardian's script)."""
    rnd = random.Random(seed)
    for i in range(count):
        a = math.tau * (i + 0.5) / count
        x, y = c + math.cos(a) * radius, c + math.sin(a) * radius
        k = rnd.randrange(5)
        s = size
        if k == 0:
            d.line([(x - s, y - s), (x + s, y + s)], fill=fill, width=1)
            d.line([(x, y - s), (x, y + s)], fill=fill, width=1)
        elif k == 1:
            d.polygon([(x, y - s), (x + s, y + s * 0.7), (x - s, y + s * 0.7)], outline=fill)
        elif k == 2:
            d.line([(x - s, y), (x + s, y)], fill=fill, width=1)
            d.line([(x - s * 0.6, y - s), (x - s * 0.6, y + s)], fill=fill, width=1)
            d.line([(x + s * 0.6, y - s), (x + s * 0.6, y + s)], fill=fill, width=1)
        elif k == 3:
            d.arc([x - s, y - s, x + s, y + s], 200, 520, fill=fill, width=1)
            d.line([(x, y), (x, y + s)], fill=fill, width=1)
        else:
            d.line([(x - s, y + s), (x, y - s), (x + s, y + s)], fill=fill, width=1)
            d.line([(x - s * 0.5, y + s * 0.2), (x + s * 0.5, y + s * 0.2)], fill=fill, width=1)


