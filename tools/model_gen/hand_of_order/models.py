"""Builds the Hand Of Order (Justiciar pathway) ModelFx models (Java block-model JSON) and their textures.

Run from the repository root:
    python3 tools/model_gen/hand_of_order/models.py src/main/resources/assets/circle_of_inevitability
then press F3+T in game. ../hanged_man/render.py draws any of them to a PNG without the game:
    python3 tools/model_gen/hanged_man/render.py src/main/resources/assets/circle_of_inevitability out.png \
        hand_of_order/brass_pillar hand_of_order/scales_stand,hand_of_order/scales_beam

Everything goes to models/model_fx/hand_of_order/ and textures/model_fx/hand_of_order/. Each JSON's "credit" says
what it is, how big, where its pivot is and how to play it; HandOfOrderFx.java plays them all. The old
models/model_fx/hand_of_order/sword.json (the first HandOfOrder class) is left alone; the Sword of Judgment here is
judgment_sword.

The model writer is the one of ../knowledge_emperor/models.py (same atlas layout, same rules, faces={...} for
single faces in another material), copied here so the Pathways can change without touching each other.

Rotations follow the right-hand rule, as in the other generators:
  axis x: +Y tilts toward +Z for a positive angle;  axis z: +Y tilts toward -X (so +X tilts toward +Y);
  axis y: +X turns toward -Z.
"""
import json
import math
