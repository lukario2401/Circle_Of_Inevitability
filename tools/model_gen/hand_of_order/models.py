def _blank(w, h=None):
    img = Image.new('RGBA', (w, h or w), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def _smooth(img, w, h=None):
    return img.resize((w, h or w), Image.LANCZOS)


def _font(px):
    """A bold serif for the spoken words; any TrueType font will do, the shape is redrawn on every run."""
    for path in ('/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf', 'C:/Windows/Fonts/timesbd.ttf',
                 '/Library/Fonts/Times New Roman Bold.ttf', 'DejaVuSerif-Bold.ttf', 'timesbd.ttf'):
        try:
            return ImageFont.truetype(path, px)
        except OSError:
            continue
    return ImageFont.load_default(px)


def _law_glyph(d, x, y, s, k, fill, width=2):
    """One of the letters of the law (k picks which): angular, upright, like an engraved code."""
    k %= 8
    if k == 0:                                                              # a section mark
        d.arc([x - s * 0.6, y - s, x + s * 0.6, y], 90, 360, fill=fill, width=width)
        d.arc([x - s * 0.6, y, x + s * 0.6, y + s], 270, 180, fill=fill, width=width)
    elif k == 1:                                                            # a pillar
        d.line([(x - s * 0.6, y - s), (x + s * 0.6, y - s)], fill=fill, width=width)
        d.line([(x - s * 0.6, y + s), (x + s * 0.6, y + s)], fill=fill, width=width)
        d.line([(x - s * 0.25, y - s), (x - s * 0.25, y + s)], fill=fill, width=width)
        d.line([(x + s * 0.25, y - s), (x + s * 0.25, y + s)], fill=fill, width=width)
    elif k == 2:                                                            # a balance
        d.line([(x, y - s), (x, y + s)], fill=fill, width=width)
        d.line([(x - s, y - s * 0.5), (x + s, y - s * 0.5)], fill=fill, width=width)
        d.arc([x - s, y - s * 0.4, x - s * 0.2, y + s * 0.3], 0, 180, fill=fill, width=width)
        d.arc([x + s * 0.2, y - s * 0.4, x + s, y + s * 0.3], 0, 180, fill=fill, width=width)
    elif k == 3:                                                            # a sword point down
        d.line([(x, y - s), (x, y + s)], fill=fill, width=width)
        d.line([(x - s * 0.6, y - s * 0.4), (x + s * 0.6, y - s * 0.4)], fill=fill, width=width)
    elif k == 4:                                                            # a closed square (a rule)
        d.rectangle([x - s * 0.7, y - s * 0.7, x + s * 0.7, y + s * 0.7], outline=fill, width=width)
        d.line([(x - s * 0.7, y), (x + s * 0.7, y)], fill=fill, width=width)
    elif k == 5:                                                            # a key of judgment
        d.ellipse([x - s * 0.45, y - s, x + s * 0.45, y - s * 0.1], outline=fill, width=width)
        d.line([(x, y - s * 0.1), (x, y + s)], fill=fill, width=width)
        d.line([(x, y + s * 0.6), (x + s * 0.5, y + s * 0.6)], fill=fill, width=width)
    elif k == 6:                                                            # three bars (decree)
        for i in (-1, 0, 1):
            d.line([(x - s * 0.7, y + i * s * 0.6), (x + s * 0.7, y + i * s * 0.6)], fill=fill, width=width)
    else:                                                                   # an eye of the law
        d.polygon([(x - s, y), (x, y - s * 0.55), (x + s, y), (x, y + s * 0.55)], outline=fill)
        d.ellipse([x - s * 0.25, y - s * 0.25, x + s * 0.25, y + s * 0.25], fill=fill)


def _glyph_ring(d, c, radius, count, fill, seed, s=8, width=2):
    rnd = random.Random(seed)
    for i in range(count):
        a = math.tau * (i + 0.5) / count
        _law_glyph(d, c + math.cos(a) * radius, c + math.sin(a) * radius, s, rnd.randrange(8), fill, width)


def _scales(d, cx, cy, s, fill, width=4):
    """A balance: post, beam and two pans."""
    d.line([(cx, cy - s), (cx, cy + s)], fill=fill, width=width)
    d.line([(cx - s * 0.5, cy + s), (cx + s * 0.5, cy + s)], fill=fill, width=width)
    d.line([(cx - s, cy - s * 0.6), (cx + s, cy - s * 0.6)], fill=fill, width=width)
    for sx in (-1, 1):
        px = cx + sx * s
        d.line([(px, cy - s * 0.6), (px - s * 0.35, cy + s * 0.05)], fill=fill, width=max(1, width // 2))
        d.line([(px, cy - s * 0.6), (px + s * 0.35, cy + s * 0.05)], fill=fill, width=max(1, width // 2))
        d.chord([px - s * 0.4, cy - s * 0.2, px + s * 0.4, cy + s * 0.3], 0, 180, fill=fill)
    d.ellipse([cx - s * 0.12, cy - s * 1.15, cx + s * 0.12, cy - s * 0.9], fill=fill)


def _sunburst(d, c, r0, r1, count, fill, width=3):
    for i in range(count):
        a = math.tau * i / count
        rr = r1 if i % 2 == 0 else r0 + (r1 - r0) * 0.6
        d.line([(c + math.cos(a) * r0, c + math.sin(a) * r0), (c + math.cos(a) * rr, c + math.sin(a) * rr)],
               fill=fill, width=width)


