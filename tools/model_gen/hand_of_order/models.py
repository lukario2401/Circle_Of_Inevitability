def word(assets, key, text):
    """A spoken word of Order: engraved capitals with a rule above and below, 3 blocks wide and 0.75 tall."""
    w, h = 384, 96
    img, d = _blank(w * 2, h * 2)
    size = 110 if len(text) <= 7 else int(110 * 7 / len(text) * 1.15)
    font = _font(size)
    cx, cy = w, h
    for dx, dy in ((-3, 0), (3, 0), (0, -3), (0, 3)):                       # a soft halo behind the letters
        d.text((cx + dx, cy + dy), text, fill=(255, 255, 255, 90), font=font, anchor='mm')
    d.text((cx, cy), text, fill=WHITE, font=font, anchor='mm')
    left, top, right, bottom = d.textbbox((cx, cy), text, font=font, anchor='mm')
    for y in (top - 18, bottom + 18):
        d.line([(left - 10, y), (right + 10, y)], fill=SOFT, width=4)
        d.polygon([(left - 26, y), (left - 10, y - 7), (left - 10, y + 7)], fill=SOFT)
        d.polygon([(right + 26, y), (right + 10, y - 7), (right + 10, y + 7)], fill=SOFT)
    img = _smooth(img, w, h)
    return write_picture_model(assets, 'word_' + key,
                               f'The word "{text}" spoken as a Verdict or a Decree: engraved capitals between two '
                               'rules, 3 blocks wide and 0.75 tall, standing (it faces north and south). White: tint '
                               'it. Pivot 8,0,8 = the middle of its bottom edge. Shown above the caster or the target '
                               'by HandOfOrderFx.speak. .glow().unshaded().seeThrough()',
                               [('word', [-16, 0, 8], [32, 12, 8], ['north', 'south'])], img)


