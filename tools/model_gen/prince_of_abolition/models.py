"""Builds the Prince Of Abolition (Black Emperor pathway) ModelFx models (Java block-model JSON) and their textures.

Run from the repository root:
    python3 tools/model_gen/prince_of_abolition/models.py src/main/resources/assets/circle_of_inevitability
then press F3+T in game. ../hanged_man/render.py draws any of them to a PNG without the game:
    python3 tools/model_gen/hanged_man/render.py src/main/resources/assets/circle_of_inevitability out.png \
        prince_of_abolition/gavel prince_of_abolition/mausoleum_0,prince_of_abolition/mausoleum_1

Everything goes to models/model_fx/prince_of_abolition/ and textures/model_fx/prince_of_abolition/. Each JSON's
"credit" says what it is, how big, where its pivot is and how to play it; PrinceOfAbolitionFx.java plays them all.

That folder also holds five older models this script does not touch: blade, entropy_disc, entropy_orb, hammer and
spear belong to the Frenzied Mage class (it was called Prince Of Abolition before), which still loads them from here.
No name below is one of those five.

The model writer is the one of ../knight_of_misfortune/models.py (same atlas layout, same rules), copied here so the
Pathways can change without touching each other, with one addition: box(..., faces={'north': 'other_material'})
gives single faces another material (the double's face, a door seen from the front).

Rotations follow the right-hand rule, as in the other generators:
  axis x: +Y tilts toward +Z for a positive angle;  axis z: +Y tilts toward -X (so +X tilts toward +Y);
  axis y: +X turns toward -Z.
"""
import json
import math
import os
import random
import sys

from PIL import Image, ImageDraw, ImageFilter

from textures import CELL, atlas

NAMESPACE = 'circle_of_inevitability'
FOLDER = 'prince_of_abolition'
ALLOWED = (-45.0, -22.5, 0.0, 22.5, 45.0)
TEX_PX_PER_MODEL_PX = CELL / 16.0          # 2 texture pixels per model pixel
CREDIT = 'Circle Of Inevitability - Prince Of Abolition '
MADE_BY = ' Generated by tools/model_gen/prince_of_abolition.'
ALL = ('north', 'south', 'east', 'west', 'up', 'down')                           # every face shows its whole cell
OLDER = ('blade', 'entropy_disc', 'entropy_orb', 'hammer', 'spear')     # the Frenzied Mage's, left alone


class Model:
    def __init__(self, name, credit, materials):
        if name in OLDER:
            raise ValueError(f'{name} is one of the Frenzied Mage models')
        self.name = FOLDER + '/' + name
        self.credit = CREDIT + credit + MADE_BY
        self.materials = materials
        self.elements = []

    def box(self, name, frm, to, mat, rot=None, full=(), skip=(), faces=None):
        """rot = (axis, angle, origin). full = faces that show their whole cell. skip = faces left out.
        faces = {face: material} for faces that use another material than 'mat'."""
        for m in [mat] + list((faces or {}).values()):
            if m not in self.materials:
                raise ValueError(f'{self.name}: material {m} is not in its atlas')
        frm = [round(v, 4) for v in frm]
        to = [round(v, 4) for v in to]
        for a, b in zip(frm, to):
            if a > b:
                raise ValueError(f'{self.name}/{name}: from > to ({frm} {to})')
            if a < -16 or b > 32:
                raise ValueError(f'{self.name}/{name}: outside -16..32 ({frm} {to})')
        if rot is not None:
            if rot[1] not in ALLOWED:
                raise ValueError(f'{self.name}/{name}: angle {rot[1]}')
            if rot[1] == 0.0:
                rot = None
        self.elements.append(dict(name=name, frm=frm, to=to, mat=mat, rot=rot, full=tuple(full), skip=tuple(skip),
                                  faces=dict(faces or {})))

    def json(self, cells, tex_w, tex_h):
        out = []
        for e in self.elements:
            (x0, y0, z0), (x1, y1, z1) = e['frm'], e['to']
            sizes = {
                'north': (x1 - x0, y1 - y0), 'south': (x1 - x0, y1 - y0),
                'east': (z1 - z0, y1 - y0), 'west': (z1 - z0, y1 - y0),
                'up': (x1 - x0, z1 - z0), 'down': (x1 - x0, z1 - z0),
            }
            faces = {}
            for face, (w, h) in sizes.items():
                if face in e['skip']:
                    continue
                cx, cy = cells[e['faces'].get(face, e['mat'])]
                if face in e['full']:
                    pw, ph = CELL, CELL
                else:
                    pw = min(CELL, max(1.0, w * TEX_PX_PER_MODEL_PX))
                    ph = min(CELL, max(1.0, h * TEX_PX_PER_MODEL_PX))
                u0 = cx * CELL / tex_w * 16
                v0 = cy * CELL / tex_h * 16
                faces[face] = {
                    'uv': [round(u0, 4), round(v0, 4), round(u0 + pw / tex_w * 16, 4), round(v0 + ph / tex_h * 16, 4)],
                    'texture': '#0',
                }
            el = {'name': e['name'], 'from': e['frm'], 'to': e['to']}
            if e['rot'] is not None:
                axis, angle, origin = e['rot']
                el['rotation'] = {'angle': angle, 'axis': axis, 'origin': [round(v, 4) for v in origin]}
            el['faces'] = faces
            out.append(el)
        return out


def save_json(assets, name, data):
    path = os.path.join(assets, 'models/model_fx', name + '.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)


def write(assets, models, tex_name, materials, seed):
    """Writes every model (several = the frames of one) sharing one atlas called tex_name."""
    img, cells = atlas(materials, seed)
    tex_w, tex_h = img.size
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, tex_name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{tex_name}'
    for m in models:
        save_json(assets, m.name, {
            'credit': m.credit,
            'texture_size': [tex_w, tex_h],
            'textures': {'0': tex_id, 'particle': tex_id},
            'elements': m.json(cells, tex_w, tex_h),
        })
    return [m.name for m in models]


def write_picture_model(assets, name, credit, elements, img, frames=1, frametime=3):
    """A model whose every face shows the whole of one picture (a flat seal, a standing sigil, a panel of fog).
    elements: [(name, from, to, faces)] or [(name, from, to, faces, (axis, angle, origin))];
    frames > 1: img holds the frames stacked downward (an animated texture)."""
    if name in OLDER:
        raise ValueError(f'{name} is one of the Frenzied Mage models')
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    meta = tex_path + '.mcmeta'
    if frames > 1:
        with open(meta, 'w') as f:
            json.dump({'animation': {'frametime': frametime, 'interpolate': True}}, f)
    elif os.path.exists(meta):
        os.remove(meta)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{name}'
    els = []
    for el in elements:
        el_name, frm, to, faces = el[:4]
        out = {'name': el_name, 'from': [round(v, 4) for v in frm], 'to': [round(v, 4) for v in to], 'shade': False}
        if len(el) > 4 and el[4] is not None and el[4][1] != 0.0:
            axis, angle, origin = el[4]
            if angle not in ALLOWED:
                raise ValueError(f'{name}/{el_name}: angle {angle}')
            out['rotation'] = {'angle': angle, 'axis': axis, 'origin': [round(v, 4) for v in origin]}
        out['faces'] = {face: {'uv': [0, 0, 16, 16], 'texture': '#0'} for face in faces}
        els.append(out)
    w = img.size[0]
    save_json(assets, FOLDER + '/' + name, {
        'credit': CREDIT + credit + MADE_BY,
        'texture_size': [w, w], 'textures': {'0': tex_id, 'particle': tex_id}, 'elements': els})
    return FOLDER + '/' + name


def centered(cx, cy, cz, sx, sy, sz):
    return [cx - sx / 2, cy - sy / 2, cz - sz / 2], [cx + sx / 2, cy + sy / 2, cz + sz / 2]


