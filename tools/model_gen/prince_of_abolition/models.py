def beam(assets):
    """A beam (Ruin, Mausoleum Salvo, Decree): two crossed planes along +Y, gold light streaming up (4 frames)."""
    size, frames = 32, 4
    img = Image.new('RGBA', (size, size * frames), (0, 0, 0, 0))
    for f in range(frames):
        frame = Image.new('RGBA', (size, size), (0, 0, 0, 0))
        px = frame.load()
        for y in range(size):
            for x in range(size):
                d = abs((x + 0.5) / size - 0.5) * 2
                streak = 0.5 + 0.5 * math.sin((y + f * size / frames) * math.tau / size * 2 + x * 0.3)
                if d < 0.18:
                    col = (255, 248, 220, 255)
                elif d < 0.55:
                    t = (d - 0.18) / 0.37
                    col = (int(255 - 30 * t), int(220 - 80 * t), int(120 - 80 * t), int(240 - 60 * t * (1 - streak)))
                else:
                    t = (d - 0.55) / 0.45
                    col = (int(60 - 40 * t), int(40 - 30 * t), int(70 - 40 * t), int((180 - 170 * t) * (0.6 + 0.4 * streak)))
                px[x, y] = col
        img.paste(frame, (0, f * size))
    return write_picture_model(assets, 'beam',
                               'a beam of command (Ruin, Mausoleum Salvo, Decree): a white-gold core, gold light '
                               'streaming along it, black-violet edges, as two crossed planes 1 block long and 1 wide '
                               'along +Y (animated). Its own colors. Pivot 8,0,8 = its start: modelAlong(level, beam, '
                               'from, direction) with .scale(width, length, width). .glow().unshaded().seeThrough()',
                               [('plane_a', [0, 0, 8], [16, 16, 8], ['north', 'south']),
                                ('plane_b', [8, 0, 0], [8, 16, 16], ['east', 'west'])], img, frames, 1)


