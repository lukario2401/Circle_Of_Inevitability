def _blank(size):
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def _crown(d, cx, base, w, h, fill, gems=None):
    """A crown outline drawn on a picture: base line at y=base, w wide, h tall, five points."""
    pts = [(cx - w / 2, base), (cx - w / 2, base - h * 0.75), (cx - w / 4, base - h * 0.45), (cx, base - h),
           (cx + w / 4, base - h * 0.45), (cx + w / 2, base - h * 0.75), (cx + w / 2, base)]
    d.polygon(pts, fill=fill)
    if gems:
        for gx in (cx - w / 4, cx, cx + w / 4):
            d.ellipse([gx - w / 16, base - h * 0.22 - w / 16, gx + w / 16, base - h * 0.22 + w / 16], fill=gems)


def _section(d, x, y, s, fill, width=1):
    """The section sign of the law: two hooked arcs one above the other."""
    d.arc([x - s, y - s * 2, x + s, y], 200, 520, fill=fill, width=width)
    d.arc([x - s, y, x + s, y + s * 2], 20, 340, fill=fill, width=width)


def _stele(d, x, y, s, fill):
    """A tiny mausoleum: a narrow slab with a pointed top."""
    d.rectangle([x - s * 0.5, y - s * 1.2, x + s * 0.5, y + s], fill=fill)
    d.polygon([(x - s * 0.7, y - s * 1.2), (x, y - s * 1.9), (x + s * 0.7, y - s * 1.2)], fill=fill)
    d.rectangle([x - s * 0.8, y + s, x + s * 0.8, y + s * 1.25], fill=fill)


def _script(d, c, radius, count, fill, seed, size=4):
    """Small marks of legal script round a circle, with a section sign every few."""
    rnd = random.Random(seed)
    for i in range(count):
        a = math.tau * (i + 0.5) / count
        x, y = c + math.cos(a) * radius, c + math.sin(a) * radius
        k = i % 5 if i % 6 else 5
        s = size
        if k == 5:
            _section(d, x, y, s * 0.6, fill)
        elif k == 0:
            d.line([(x - s, y - s), (x + s, y - s), (x, y + s)], fill=fill, width=1)
        elif k == 1:
            d.arc([x - s, y - s, x + s, y + s], 40, 320, fill=fill, width=1)
            d.line([(x, y - s), (x, y + s)], fill=fill, width=1)
        elif k == 2:
            d.line([(x - s, y + s), (x, y - s), (x + s, y + s)], fill=fill, width=1)
            d.line([(x - s * 0.5, y), (x + s * 0.5, y)], fill=fill, width=1)
        elif k == 3:
            d.rectangle([x - s * 0.6, y - s * 0.6, x + s * 0.6, y + s * 0.6], outline=fill)
        else:
            d.line([(x - s, y), (x + s, y)], fill=fill, width=1)
            d.line([(x + rnd.uniform(-s, s), y - s), (x + rnd.uniform(-s, s), y + s)], fill=fill, width=1)


