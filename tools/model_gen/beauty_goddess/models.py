def moon_halo(assets):
    size = 128
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c = size / 2
    for r, a, w in ((60, 120, 2), (54, 255, 2), (48, 90, 1)):
        d.ellipse([c - r, c - r, c + r, c + r], outline=(255, 255, 255, a), width=w)
    for i in range(16):                                            # rays
        ang = math.tau * i / 16
        r0, r1 = (36, 46) if i % 2 == 0 else (40, 45)
        d.line([(c + math.cos(ang) * r0, c + math.sin(ang) * r0), (c + math.cos(ang) * r1, c + math.sin(ang) * r1)],
               fill=(255, 255, 255, 200), width=1)
    for i in range(4):                                             # four small crescents on the ring
        ang = math.tau * i / 4 + math.pi / 4
        x, y = c + math.cos(ang) * 54, c + math.sin(ang) * 54
