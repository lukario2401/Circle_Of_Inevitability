    c = size / 2
    white = (255, 255, 255, 255)
    soft = (255, 255, 255, 140)
    # a six-pointed star of two triangles, a big crescent in its middle and a bat over it
    for k in range(2):
        pts = [(c + math.cos(math.tau * i / 3 + k * math.pi / 3 - math.pi / 2) * 46,
                c + math.sin(math.tau * i / 3 + k * math.pi / 3 - math.pi / 2) * 46) for i in range(3)]
        d.polygon(pts, outline=white)
        d.line(pts + [pts[0]], fill=white, width=2)
    d.ellipse([c - 30, c - 30, c + 30, c + 30], outline=soft, width=1)
    big = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    bd = ImageDraw.Draw(big)
    bd.ellipse([c - 22, c - 22, c + 22, c + 22], fill=white)
    bd.ellipse([c - 14, c - 26, c + 30, c + 18], fill=(0, 0, 0, 0))
    img.alpha_composite(big)
    # the bat: a body and two scalloped wings
    bat = [(c, c - 4), (c + 6, c - 10), (c + 18, c - 12), (c + 14, c - 6), (c + 20, c - 2), (c + 10, c),
           (c + 4, c + 2), (c, c + 6), (c - 4, c + 2), (c - 10, c), (c - 20, c - 2), (c - 14, c - 6), (c - 18, c - 12),
           (c - 6, c - 10)]
