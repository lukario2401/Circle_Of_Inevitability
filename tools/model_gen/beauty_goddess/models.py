def spirit_door_void(assets):
    """The inside of the doorway: the Spirit World swirling, with stars and a far light. 8 frames, animated."""
    size, frames = 64, 8
    img = Image.new('RGBA', (size, size * frames), (0, 0, 0, 0))
    px = img.load()
    rnd = random.Random(41)
    stars = [(rnd.random() * size, rnd.random() * size, rnd.random()) for _ in range(40)]
    for f in range(frames):
        phase = f / frames * math.tau
        for y in range(size):
            for x in range(size):
                dx, dy = (x - size / 2) / (size / 2), (y - size * 0.62) / (size / 2)
                r = math.hypot(dx, dy)
                a = math.atan2(dy, dx)
                swirl = math.sin(a * 3 + r * 7 - phase) * 0.5 + 0.5
                t = max(0.0, 1 - r)
                c = mix(rgba('0a0620'), rgba('5a3ac8'), swirl * 0.6 + t * 0.4)
                c = mix(c, rgba('e8e0ff'), max(0.0, t - 0.6) * 2.2)
                px[x, y + f * size] = c[:3] + (235,)
        d = ImageDraw.Draw(img)
        for sx, sy, b in stars:
            tw = 0.5 + 0.5 * math.sin(phase * 2 + b * 9)
            c = mix(rgba('8a7ac8'), rgba('ffffff'), tw)
            d.point((sx, sy + f * size), fill=c)
    return write_picture_model(assets, 'spirit_door_void',
                               'spirit door void: the Spirit World seen through the Door of Summoning, swirling violet with '
                               'stars and a far light, animated; fills the doorway (2.25 x 2.1 blocks). Pivot 8,-16,8 like '
                               'the frame. Play it .glow().unshaded().seeThrough(); scale its y from 0 to open it.',
                               [('void', [-10, -14.6, 7.9], [26, 19, 8.1], ['north', 'south'])], img, frames, 3)


