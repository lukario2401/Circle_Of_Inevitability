def abyss_pool(assets):
    size = 64
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    px = img.load()
    rnd = random.Random(7)
    wobble = [rnd.uniform(-0.08, 0.08) for _ in range(12)]
    for y in range(size):
        for x in range(size):
            dx, dy = (x + 0.5) / size * 2 - 1, (y + 0.5) / size * 2 - 1
            r = math.hypot(dx, dy)
            a = (math.atan2(dy, dx) / math.tau + 0.5) * 12
            edge_r = 0.86 + wobble[int(a) % 12] * (1 - (a % 1)) + wobble[(int(a) + 1) % 12] * (a % 1)
            if r > edge_r:
                continue
            rim = max(0.0, (r - edge_r + 0.14) / 0.14)
            c = mix(rgba('020008', 245), rgba('1a0a2a', 235), r)
            c = mix(c, rgba('a040ff', 250), rim ** 2)
            px[x, y] = c
    return write_picture_model(assets, 'abyss_pool',
                               'abyss pool: a ragged pool of darkness with a violet glowing rim, 1 block wide, flat. '
                               'Pivot 8,0,8 = its middle; .scale(w) = w blocks wide. .glow().unshaded().seeThrough()',
                               [('pool', [0, 0, 0], [16, 0, 16], ['up', 'down'])], img)


