# 4. Abyss Shackles: a cuff of black iron round the bound one, and a chain of darkness from the ground
# =====================================================================================================

def abyss_shackle():
    mats = ['abyss_iron', 'shackle_rune', 'abyss_glow']
    m = Model('abyss_shackle',
              'abyss shackle: a cuff of black iron with violet crescents, a ring 1.1 blocks across round a 1-block '
              'middle. Pivot 8,8,8 = the middle of the ring. Scale it to the bound one\'s width. Play it .glow().',
              mats)
    r = 8.6
    side = 2 * r * math.tan(math.radians(22.5)) + 0.4
    for k in range(8):
        base = k if k % 2 == 0 else k - 1
        theta = math.radians(45 * base)
        cx, cz = 8 + r * math.cos(theta), 8 + r * math.sin(theta)
        if base % 4 == 0:            # 0 or 180 degrees: the band runs along z
            size = (1.6, 2.6, side)
        else:                        # 90 or 270: along x
            size = (side, 2.6, 1.6)
        rot = ('y', -45.0, [8, 8, 8]) if k % 2 == 1 else None
        m.box(f'band{k}', *centered(cx, 8, cz, *size), 'shackle_rune' if k % 2 == 0 else 'abyss_iron', rot)
        if k % 2 == 0:
            out = 1.0
            gx, gz = 8 + (r + out) * math.cos(theta), 8 + (r + out) * math.sin(theta)
            m.box(f'stud{k}', *centered(gx, 8, gz, 0.8, 1.0, 0.8), 'abyss_glow')
    return [m], mats


def abyss_chain():
    mats = ['chain_link', 'abyss_iron']
    m = Model('abyss_chain',
              'abyss chain: a chain of condensed darkness, 3 blocks long, standing up. Pivot 8,-16,8 = its lower end. '
              'For modelAlong (its top points the way); .scale(1, length / 3, 1) stretches it. Play it .glow().seeThrough().',
              mats)
    link, step = 4.4, 3.2
    y = -16.0
    i = 0
    while y + link <= 32.01:
        if i % 2 == 0:
            m.box(f'link{i}', [6.6, y, 7.7], [9.4, y + link, 8.3], 'chain_link', full=('north', 'south'),
                  skip=('east', 'west', 'up', 'down'))
