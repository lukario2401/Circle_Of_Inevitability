def gravity_well(assets):
    size, frames = 192, 6
    out = []
    for f in range(frames):
        big = size * 2
        img, d = blank(big)
        c = big / 2
        phase = f / frames
        for k in range(7):                                                 # rings sinking toward the middle
            t = ((k + 1 - phase) / 7)
            r = 12 + 368 * t ** 1.6
            a = int(255 * min(1.0, (1 - t) * 1.6) * min(1.0, t * 5))
            ring(d, c, r, (255, 255, 255, a), 3 + int(4 * (1 - t)))
        for arm in range(8):                                               # lines bent by the weight
            pts = []
            for i in range(40):
                t = i / 39
                r = 30 + 350 * t
                a = math.tau * arm / 8 + (1 - t) ** 2 * 2.2 + phase * math.tau / 8
                pts.append((c + math.cos(a) * r, c + math.sin(a) * r))
            d.line(pts, fill=(255, 255, 255, 90), width=3)
        glow_dot(d, c, c, 14)
        out.append(disc_mask(smooth(img, size)))
    return write_picture_model(assets, 'gravity_well',
                               'A gravity well: rings sinking toward the middle and eight lines bent round it '
                               '(animated); 1 block wide, lying flat. White: tint it deep indigo for Pressed, pale blue '
                               'for Lifted (and spin it the other way). Pivot 8,0,8. Gravity Abnormality, Heavybringing, '
                               'the Neutron Star, Time Dilation. .glow().unshaded().seeThrough()', FLAT,
                               animated(out, size), frames, 3)


