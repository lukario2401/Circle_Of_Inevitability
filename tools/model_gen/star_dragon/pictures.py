def void_door(assets):
    size, frames = 64, 4
    rnd = random.Random(31)
    pts = [(rnd.uniform(24, 40), rnd.uniform(6, 58), rnd.uniform(0.5, 1.4), rnd.randrange(4)) for _ in range(26)]
    out = []
    for f in range(frames):
        img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
        px = img.load()
        for y in range(size):
            for x in range(size):
                v = (y + 0.5) / size * 2 - 1
                half = 14 * (1 - v * v) ** 0.8                              # an almond slit, tall
                dx = abs(x + 0.5 - 32)
                if dx > half + 3:
                    continue
                if dx > half:
                    t = (dx - half) / 3
                    px[x, y] = (170, 150, 255, int(230 * (1 - t)))
                else:
                    deep = dx / max(half, 0.01)
                    px[x, y] = (int(10 + 30 * deep), int(8 + 20 * deep), int(30 + 70 * deep), 245)
        d = ImageDraw.Draw(img)
        for x, y, r, phase in pts:
            v = (y + 0.5) / size * 2 - 1
            if abs(x - 32) > 13 * (1 - v * v) ** 0.8:
                continue
            tw = 0.5 + 0.5 * math.cos((f + phase) * math.pi / 2)
            d.ellipse([x - r * 0.6, y - r * 0.6, x + r * 0.6, y + r * 0.6], fill=(255, 255, 255, int(110 + 145 * tw)))
        out.append(img)
    return write_picture_model(assets, 'void_door',
                               'Void Passage\'s door: a tall almond slit into the void, indigo-black with stars that '
                               'twinkle (animated) and a rim of violet light; 1 block, standing. Its own colors. '
                               'Pivot 8,0,8 = the middle of its foot: .scale(1.4f, 2.4f, 1f). '
                               '.glow().unshaded().seeThrough()', STANDING, animated(out, size), frames, 4)


def _beam(assets, name, credit, core, rim_power, rings, seed):
    size, frames = 32, 4
    out = []
    rnd = random.Random(seed)
    motes = [(rnd.uniform(4, 28), rnd.uniform(0, 32)) for _ in range(8)]
    for f in range(frames):
        img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
        px = img.load()
        for y in range(size):
            for x in range(size):
                dx = abs((x + 0.5) / size - 0.5) * 2
                wave = 0.06 * math.sin((y + f * size / frames) / size * math.tau * 2 + x * 0.3)
                body = max(0.0, 1 - (dx + wave)) ** (1.0 / rim_power)
                hot = max(0.0, 1 - dx / core) if dx < core else 0.0
                band = 0.0
                if rings:
                    band = max(0.0, 1 - abs(((y + f * size / frames) % (size / 2)) - size / 4) / 2.0) * (1 - dx)
                a = min(1.0, body * 0.5 + hot * 0.7 + band * 0.4)
                px[x, y] = (255, 255, 255, int(255 * a))
        d = ImageDraw.Draw(img)
        for mx, my in motes:
            yy = (my - f * 4) % size
            d.point((mx, yy), fill=(255, 255, 255, 255))
        out.append(img)
    return write_picture_model(assets, name, credit, CROSSED, animated(out, size), frames, 2)


