def time_field(assets):
    size, frames = 256, 4
    out = []
    for f in range(frames):
        big = size * 2
        img, d = blank(big)
        c = big / 2
        for k, r in enumerate((246, 200, 150, 100, 56)):                    # rings of a clock, each slower inside
            ring(d, c, r, SOFT if k else WHITE, 4 if k == 0 else 2)
            turn = f / frames * math.tau / 12 / (k + 1)
            count = 12 * (5 - k) if k < 4 else 4
            for i in range(count):
                a = turn + math.tau * i / count
                l = 14 if i % (count // 4 or 1) == 0 else 7
                d.line([(c + math.cos(a) * (r - l), c + math.sin(a) * (r - l)), (c + math.cos(a) * r, c + math.sin(a) * r)],
                       fill=WHITE, width=3)
        for i in range(-4, 5):                                             # space-time, bent toward the middle
            pts_h, pts_v = [], []
            for j in range(41):
                t = j / 40 * 2 - 1
                x0, y0 = t * 240, i * 56
                pull = 1 - 0.35 * math.exp(-(x0 * x0 + y0 * y0) / 18000)
                pts_h.append((c + x0 * pull, c + y0 * pull))
                pts_v.append((c + y0 * pull, c + x0 * pull))
            d.line(pts_h, fill=FAINT, width=2)
            d.line(pts_v, fill=FAINT, width=2)
        a = f / frames * math.tau / 12                                      # one slow hand
        d.line([(c, c), (c + math.cos(a - math.pi / 2) * 180, c + math.sin(a - math.pi / 2) * 180)], fill=WHITE, width=5)
        glow_dot(d, c, c, 10)
        out.append(disc_mask(smooth(img, size)))
    return write_picture_model(assets, 'time_field',
                               'Gravitational Time Dilation: the rings of a clock, each slower than the one outside it, '
                               'a single slow hand and a grid of space-time bent toward the middle (animated, barely '
                               'moving); 1 block wide, lying flat. White: tint it pale violet. Pivot 8,0,8. '
                               '.glow().unshaded().seeThrough()', FLAT, animated(out, size), frames, 10)


def quantum_field(assets):
    size, frames = 192, 4
    out = []
    for f in range(frames):
        rnd = random.Random(70 + f)
        big = size * 2
        img, d = blank(big)
        c = big / 2
        s1, s2 = (c - 60, c), (c + 60, c)
        px = img.load()
        for y in range(0, big, 2):                                         # two waves interfering
            for x in range(0, big, 2):
                if math.hypot(x - c, y - c) > 370:
                    continue
                r1, r2 = math.hypot(x - s1[0], y - s1[1]), math.hypot(x - s2[0], y - s2[1])
                v = math.cos((r1 - r2) / 14 + f * math.pi / 2) * math.cos((r1 + r2) / 30 - f * math.pi / 2)
                if v > 0.55:
                    a = int(110 * (v - 0.55) / 0.45)
                    for dx in (0, 1):
                        for dy in (0, 1):
                            px[x + dx, y + dy] = (255, 255, 255, a)
        for _ in range(70):                                                # where it might be
            r, a = 360 * math.sqrt(rnd.random()), rnd.random() * math.tau
            glow_dot(d, c + math.cos(a) * r, c + math.sin(a) * r, rnd.uniform(2, 5), 230)
        ring(d, c, 370, SOFT, 3)
        out.append(disc_mask(smooth(img, size)))
    return write_picture_model(assets, 'quantum_field',
                               'Quantum Uncertainty: fringes of two waves interfering and a scatter of bright points '
                               'that jump about every frame (animated); 1 block wide, lying flat. White: tint it. '
                               'Pivot 8,0,8. .glow().unshaded().seeThrough()', FLAT, animated(out, size), frames, 2)


def accretion_disk(assets):
    size, frames = 256, 6
    out = []
    for f in range(frames):
        img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
        px = img.load()
        for y in range(size):
            for x in range(size):
                dx, dy = (x + 0.5) / size - 0.5, (y + 0.5) / size - 0.5
                r = math.hypot(dx, dy) * 2
                if r > 1 or r < 0.3:
                    continue
                ang = math.atan2(dy, dx)
                swirl = 0.5 + 0.5 * math.sin(ang * 5 + 9 / (r + 0.15) - f / frames * math.tau)
                heat = (1 - (r - 0.3) / 0.7)
                edge = min(1.0, (r - 0.3) / 0.05) * min(1.0, (1 - r) / 0.25)
                col = (255, int(150 + 105 * heat), int(60 + 195 * heat ** 2))
                a = (0.35 + 0.65 * swirl) * heat ** 0.6 * edge
                px[x, y] = col + (int(255 * a),)
        out.append(img)
    return write_picture_model(assets, 'accretion_disk',
                               'The Singularity\'s accretion disc: a swirl of matter round a dark hole, white-hot at the '
                               'inner edge and orange-gold outward, turning (animated); 1 block wide, lying flat. Its '
                               'own colors. Pivot 8,0,8. Lay it round black_hole, a little tipped. '
                               '.glow().unshaded().seeThrough()', FLAT, animated(out, size), frames, 2)


