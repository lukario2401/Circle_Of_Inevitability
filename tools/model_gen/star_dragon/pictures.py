"""The Star Dragon's picture models: models whose faces each show one whole picture (a circle on the ground, a ray,
a gravity well, the accretion disc, a mark over a head). Run by models.py; on its own:
    python3 tools/model_gen/star_dragon/pictures.py src/main/resources/assets/circle_of_inevitability

White pictures take any tint with .color(...); the ones that keep their own colors say so in their credit.
Each picture is drawn at twice its size and brought down, for soft edges.
"""
import json
import math
import os
import random
import sys

from PIL import Image, ImageDraw

NAMESPACE = 'circle_of_inevitability'
FOLDER = 'star_dragon'
ALLOWED = (-45.0, -22.5, 0.0, 22.5, 45.0)
CREDIT = 'Circle Of Inevitability - Star Dragon '
MADE_BY = ' Generated by tools/model_gen/star_dragon.'

WHITE = (255, 255, 255, 255)
SOFT = (255, 255, 255, 150)
FAINT = (255, 255, 255, 80)

FLAT = [('plate', [0, 0, 0], [16, 0, 16], ['up', 'down'])]
STANDING = [('plate', [0, 0, 8], [16, 16, 8], ['north', 'south'])]
CROSSED = [('a', [0, 0, 8], [16, 16, 8], ['north', 'south']),
           ('b', [8, 0, 0], [8, 16, 16], ['east', 'west'])]


def save_json(assets, name, data):
    path = os.path.join(assets, 'models/model_fx', name + '.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)


def write_picture_model(assets, name, credit, elements, img, frames=1, frametime=3, tex_name=None):
    """A model whose every face shows the whole of one picture. frames > 1: img holds the frames stacked downward
    (an animated texture). tex_name: the picture's file name when it differs from the model's."""
    tex_name = tex_name or name
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, tex_name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    meta = tex_path + '.mcmeta'
    if frames > 1:
        with open(meta, 'w') as f:
            json.dump({'animation': {'frametime': frametime, 'interpolate': True}}, f)
    elif os.path.exists(meta):
        os.remove(meta)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{tex_name}'
    els = []
    for el in elements:
        el_name, frm, to, faces = el[:4]
        out = {'name': el_name, 'from': [round(v, 4) for v in frm], 'to': [round(v, 4) for v in to], 'shade': False}
        if len(el) > 4 and el[4] is not None and el[4][1] != 0.0:
            axis, angle, origin = el[4]
            if angle not in ALLOWED:
                raise ValueError(f'{name}/{el_name}: angle {angle}')
            out['rotation'] = {'angle': angle, 'axis': axis, 'origin': [round(v, 4) for v in origin]}
        out['faces'] = {face: {'uv': [0, 0, 16, 16], 'texture': '#0'} for face in faces}
        els.append(out)
    w = img.size[0]
    save_json(assets, FOLDER + '/' + name, {
        'credit': CREDIT + credit + MADE_BY,
        'texture_size': [w, w], 'textures': {'0': tex_id, 'particle': tex_id}, 'elements': els})
    return FOLDER + '/' + name


def blank(size):
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def smooth(img, size):
    return img.resize((size, size), Image.LANCZOS)


def animated(frames_list, size):
    img = Image.new('RGBA', (size, size * len(frames_list)), (0, 0, 0, 0))
    for i, f in enumerate(frames_list):
        img.paste(f, (0, i * size))
    return img


def star_point(d, x, y, r, fill, points=4, inner=0.38, turn=0.0):
    pts = []
    for i in range(points * 2):
        a = -math.pi / 2 + turn + math.pi * i / points
        rr = r if i % 2 == 0 else r * inner
        pts.append((x + math.cos(a) * rr, y + math.sin(a) * rr))
    d.polygon(pts, fill=fill)


def ticks(d, c, r0, r1, count, fill, width=2, every=0, long=0):
    for i in range(count):
        a = math.tau * i / count
        rr0 = r0 - (long if every and i % every == 0 else 0)
        d.line([(c + math.cos(a) * rr0, c + math.sin(a) * rr0), (c + math.cos(a) * r1, c + math.sin(a) * r1)],
               fill=fill, width=width)


def ring(d, c, r, fill, width, cy=None):
    cy = c if cy is None else cy
    d.ellipse([c - r, cy - r, c + r, cy + r], outline=fill, width=width)


def disc_mask(img, margin=1):
    size = img.size[0]
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).ellipse([margin, margin, size - 1 - margin, size - 1 - margin], fill=255)
    cut = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    cut.paste(img, (0, 0), mask)
    return cut


def glow_dot(d, x, y, r, alpha=255):
    for k in range(3, 0, -1):
        rr = r * (1 + k * 0.6)
        d.ellipse([x - rr, y - rr, x + rr, y + rr], fill=(255, 255, 255, int(alpha * 0.18 * (4 - k) / 3)))
    d.ellipse([x - r, y - r, x + r, y + r], fill=(255, 255, 255, alpha))


