def astrolabe(assets):
    size = 256
    big = size * 2
    img, d = blank(big)
    c = big / 2
    rnd = random.Random(11)
    for r, w, col in ((250, 6, WHITE), (238, 2, SOFT), (200, 3, SOFT), (150, 2, FAINT), (96, 3, SOFT)):
        ring(d, c, r, col, w)
    ticks(d, c, 238, 250, 120, SOFT, 2, 10, 14)
    for k in range(12):                                                    # the twelve houses of the sky
        a = math.tau * k / 12
        d.line([(c + math.cos(a) * 96, c + math.sin(a) * 96), (c + math.cos(a) * 200, c + math.sin(a) * 200)],
               fill=FAINT, width=2)
        star_point(d, c + math.cos(a + 0.26) * 222, c + math.sin(a + 0.26) * 222, 8, SOFT)
    d.ellipse([c - 220, c - 120, c + 160, c + 150], outline=SOFT, width=3)  # the ecliptic, off center
    d.ellipse([c - 130, c - 200, c + 110, c + 90], outline=FAINT, width=2)
    figures = []
    for _ in range(4):                                                     # constellations within
        cx, cy = c + rnd.uniform(-110, 110), c + rnd.uniform(-110, 110)
        pts = [(cx + rnd.uniform(-46, 46), cy + rnd.uniform(-46, 46)) for _ in range(4)]
        figures.append(pts)
    for pts in figures:
        d.line(pts, fill=SOFT, width=2)
        for p in pts:
            glow_dot(d, p[0], p[1], 4)
    glow_dot(d, c, c, 10)
    star_point(d, c, c, 26, WHITE, 4, 0.25)
    return write_picture_model(assets, 'astrolabe',
                               'Star Chart\'s astrolabe: rings and degree ticks, the twelve houses with a star in each, '
                               'two tilted orbits, constellations drawn between bright stars and a four-pointed star in '
                               'the middle; 1 block wide, lying flat. White: tint it star white or the Pathway\'s violet. '
                               'Pivot 8,0,8 = its middle. Stand it up with pitch 90. .glow().unshaded().seeThrough()',
                               FLAT, smooth(img, size))


