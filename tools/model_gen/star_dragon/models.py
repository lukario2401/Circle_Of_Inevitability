        m.box(f'v_w{turn:.0f}', [2.2, 3.6, 7.5], [3.0, 12.4, 8.5], 'magnetic_ring', rot)
        m.box(f'v_e{turn:.0f}', [13.0, 3.6, 7.5], [13.8, 12.4, 8.5], 'magnetic_ring', rot)
