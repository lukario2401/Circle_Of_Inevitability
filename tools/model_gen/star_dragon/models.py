def fusion_cluster():
    m = Model('fusion_cluster',
              'A magnetically confined fusion cluster: a ball of white-hot plasma inside two rings of violet-blue '
              'magnetic light (one level, one upright); 1 block. Pivot 8,8,8 = the core. Top = its front for a Shot. '
              '.spin(...) turns the rings. .glow().unshaded().seeThrough()',
              STAR_MATS)
    ball(m, 'core', 8, 8, 8, 6.0, 'fusion_core')
    for turn in (0.0, 45.0):                                                   # a level octagon of bars
        rot = ('y', turn, [8, 8, 8]) if turn else None
        m.box(f'h_n{turn:.0f}', [3.0, 7.5, 1.8], [13.0, 8.5, 2.6], 'magnetic_ring', rot)
        m.box(f'h_s{turn:.0f}', [3.0, 7.5, 13.4], [13.0, 8.5, 14.2], 'magnetic_ring', rot)
        m.box(f'h_w{turn:.0f}', [1.8, 7.5, 3.0], [2.6, 8.5, 13.0], 'magnetic_ring', rot)
        m.box(f'h_e{turn:.0f}', [13.4, 7.5, 3.0], [14.2, 8.5, 13.0], 'magnetic_ring', rot)
    for turn in (0.0, 45.0):                                                   # and an upright one
        rot = ('z', turn, [8, 8, 8]) if turn else None
        m.box(f'v_t{turn:.0f}', [3.6, 13.0, 7.5], [12.4, 13.8, 8.5], 'magnetic_ring', rot)
