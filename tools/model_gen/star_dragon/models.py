ROCK_MATS = ['asteroid_rock', 'asteroid_ember', 'flame_wrap']


def asteroid():
    rock = Model('asteroid',
                 'A grazed asteroid: a pitted lump of dark stone, its leading face glowing white-orange from the fall '
                 'and seams of fire cracking it; about 1 block. Top = its front (the hot face leads). Pivot 8,8,8 = '
                 'its middle. Drop it head first (modelAlong straight down, or pitch 180) and play asteroid_flame '
                 'with the same keys for the fire round it. .scale(...) for Planetfall. .glow()',
                 ROCK_MATS)
    hot = {'up': 'asteroid_ember'}
    ball(rock, 'core', 8, 8, 8, 10.0, 'asteroid_rock')
    rock.box('cap', *centered(8, 12.6, 8, 7.0, 1.6, 7.0), 'asteroid_ember', ('y', 22.5, [8, 12.6, 8]))
    rock.box('lump_a', *centered(4.6, 9.6, 6.6, 5.0, 5.0, 5.4), 'asteroid_rock', ('y', 22.5, [4.6, 9.6, 6.6]), faces=hot)
    rock.box('lump_b', *centered(11.4, 6.2, 9.2, 5.0, 5.6, 5.0), 'asteroid_rock', ('x', 22.5, [11.4, 6.2, 9.2]))
    rock.box('lump_c', *centered(9.2, 11.0, 11.4, 4.6, 3.8, 4.0), 'asteroid_rock', ('z', -22.5, [9.2, 11.0, 11.4]),
             faces=hot)
    rock.box('lump_d', *centered(6.2, 4.6, 10.6, 4.2, 3.6, 4.4), 'asteroid_rock', ('x', -22.5, [6.2, 4.6, 10.6]))
    rock.box('lump_e', *centered(10.6, 9.0, 4.0, 3.6, 4.0, 3.4), 'asteroid_rock', ('z', 22.5, [10.6, 9.0, 4.0]),
             faces=hot)
    flame = Model('asteroid_flame',
                  'The fire wrapped round a falling asteroid: four planes of flame, white-gold at the rock and orange '
                  'toward the tip, streaming 1.6 blocks behind it (down = behind). Play it with exactly the asteroid\'s '
                  'scale and keys. Pivot 8,8,8 = the rock\'s middle. .glow().unshaded().seeThrough()',
                  ROCK_MATS)
    plate_ns(flame, 'a', 1.0, -16.0, 15.0, 14.0, 8.0, 'flame_wrap')
    plate_ew(flame, 'b', 1.0, -16.0, 15.0, 14.0, 8.0, 'flame_wrap')
    plate_ns(flame, 'c', 2.0, -14.0, 14.0, 13.0, 8.0, 'flame_wrap', ('y', 45.0, [8, 0, 8]))
    plate_ew(flame, 'd', 2.0, -14.0, 14.0, 13.0, 8.0, 'flame_wrap', ('y', 45.0, [8, 0, 8]))
    return [rock, flame], ROCK_MATS


