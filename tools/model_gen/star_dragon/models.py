def neutron_star():
    m = Model('neutron_star',
              'The Neutron Star: a small blinding blue-white core with the two beams of a pulsar streaming from its '
              'poles, 1.4 blocks up and 1.4 down. Pivot 8,8,8 = the core. Worn at the chest (modelOn); tilt it '
              '(roll) and .spin(...) so the beams sweep round. .glow().unshaded().seeThrough()',
              STAR_MATS)
    ball(m, 'core', 8, 8, 8, 4.0, 'neutron_core')
    ball(m, 'halo', 8, 8, 8, 6.0, 'star_spike')
    plate_ns(m, 'up_a', 6.0, 10.0, 10.0, 32.0, 8.0, 'pulsar_beam_up')
