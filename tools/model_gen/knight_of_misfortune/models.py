def vortex(assets):
    """Destination of All Things: arms of darkness spiralling into a black middle (4 frames, turning)."""
    size, frames = 160, 4
    img = Image.new('RGBA', (size, size * frames), (0, 0, 0, 0))
    c = size / 2
    for f in range(frames):
        frame = Image.new('RGBA', (size, size), (0, 0, 0, 0))
        px = frame.load()
        turn = f * math.tau / frames / 3
        for y in range(size):
            for x in range(size):
                dx, dy = x + 0.5 - c, y + 0.5 - c
                r = math.hypot(dx, dy) / c
                if r > 1:
                    continue
                a = math.atan2(dy, dx)
                arm = 0.5 + 0.5 * math.cos(5 * (a + turn) + 9 * r)
                if r < 0.18:
                    px[x, y] = (0, 0, 0, 255)
                    continue
                light = arm * (1 - r) ** 0.5
                col = (int(20 + 170 * light), int(6 + 90 * light), int(34 + 210 * light))
                alpha = int(255 * min(1.0, (1 - r) * 3) * (0.55 + 0.45 * arm))
                px[x, y] = col + (alpha,)
        d = ImageDraw.Draw(frame)
        d.ellipse([c - 0.19 * c - 2, c - 0.19 * c - 2, c + 0.19 * c + 2, c + 0.19 * c + 2], outline=(230, 210, 255, 255),
                  width=2)
        img.paste(frame, (0, f * size))
    return write_picture_model(assets, 'vortex',
                               'Destination of All Things: arms of violet darkness spiralling into a black middle with '
                               'a thin pale rim (animated), 1 block wide. Its own colors. Lies flat; also good standing '
                               '(pitch 90) as a black hole. Pivot 8,0,8 = its middle. .seeThrough().unshaded(), and '
                               '.spin(-4) to turn it the way the arms curl.', FLAT, img, frames, 3)


