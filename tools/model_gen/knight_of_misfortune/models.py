def _blank(size):
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def _star(d, x, y, r, fill, points=4, inner=0.35):
    pts = []
    for i in range(points * 2):
        a = math.pi * i / points - math.pi / 2
        rr = r if i % 2 == 0 else r * inner
        pts.append((x + math.cos(a) * rr, y + math.sin(a) * rr))
    d.polygon(pts, fill=fill)


def _crescent(img, cx, cy, r, fill, cut=0.55, turn=0.0):
    """A crescent moon on img: a disc with another, shifted toward 'turn' (radians), cut out of it."""
    mask = Image.new('L', img.size, 0)
    md = ImageDraw.Draw(mask)
    md.ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)
    ox, oy = cx + math.cos(turn) * r * cut, cy + math.sin(turn) * r * cut
    md.ellipse([ox - r * 0.92, oy - r * 0.92, ox + r * 0.92, oy + r * 0.92], fill=0)
    layer = Image.new('RGBA', img.size, fill)
    img.paste(Image.alpha_composite(img, layer), (0, 0), mask)


def _glyphs(d, c, radius, count, fill, seed, size=4):
    """Small flowing runes round a circle: the script of the Midnight Poems and the seals of Darkness."""
    rnd = random.Random(seed)
    for i in range(count):
        a = math.tau * (i + 0.5) / count
        x, y = c + math.cos(a) * radius, c + math.sin(a) * radius
        k = rnd.randrange(5)
        s = size
        if k == 0:
            d.arc([x - s, y - s, x + s, y + s], 30, 300, fill=fill, width=1)
        elif k == 1:
            d.line([(x - s, y + s), (x, y - s), (x + s, y + s)], fill=fill, width=1)
            d.point((x, y + s * 0.2), fill=fill)
        elif k == 2:
            d.arc([x - s, y - s, x + s, y], 180, 360, fill=fill, width=1)
            d.line([(x, y - s * 0.5), (x, y + s)], fill=fill, width=1)
        elif k == 3:
            d.ellipse([x - s * 0.5, y - s * 0.5, x + s * 0.5, y + s * 0.5], outline=fill)
            d.line([(x - s, y + s), (x + s, y - s)], fill=fill, width=1)
        else:
            d.line([(x - s, y), (x + s, y)], fill=fill, width=1)
            d.arc([x - s, y - s, x + s, y + s], 0, 180, fill=fill, width=1)


