TOTEM_MATS = ['totem_wood', 'totem_carving', 'totem_face', 'totem_eye', 'moss', 'feather', 'earth']


def totem():
    m = Model('totem',
              'Totem Territory\'s totem: a carved wooden pole 2 blocks tall on a mound of earth, bands of zigzag '
              'carving, a carved face on every side, a pair of carved boards spread like wings, moss in its cracks, '
              'feathers hanging from the boards and a great watching eye (cream, moss-green iris) near the top, '
              'facing front. Pivot 8,0,8 = its foot. Let it rise out of the ground (key up from -2). .glow()',
              TOTEM_MATS)
    m.box('mound', [3.0, -1.0, 3.0], [13.0, 1.2, 13.0], 'earth')
    m.box('mound_t', [4.0, -1.0, 4.0], [12.0, 1.8, 12.0], 'earth', ('y', 45.0, [8, 0, 8]))
    octagon_y(m, 'pole', 8, 8, 0.0, 26.0, 5.6, 'totem_wood')
    for i, y in enumerate((2.0, 9.5, 17.0)):                                  # carved bands
        m.box(f'band_{i}', [4.6, y, 4.6], [11.4, y + 3.2, 11.4], 'totem_carving')
    m.box('face', [4.4, 5.4, 4.4], [11.6, 9.4, 11.6], 'totem_face')           # a face on every side
    m.box('face_2', [4.8, 12.8, 4.8], [11.2, 16.8, 11.2], 'totem_face')
    for side, sign in (('l', -1), ('r', 1)):                                 # the wing boards
        x0, x1 = (8 - 12.5, 8 - 3.0) if sign < 0 else (8 + 3.0, 8 + 12.5)
        m.box(f'board_{side}', [x0, 20.0, 7.0], [x1, 22.6, 9.0], 'totem_carving',
              ('z', 22.5 * sign, [8 + sign * 3.0, 21.3, 8]))
        for k in range(3):                                                    # feathers hanging off them
            fx = 8 + sign * (5.0 + k * 3.0)
            plate_ns(m, f'feather_{side}{k}', fx - 0.9, 13.0 + k * 1.2, fx + 0.9, 19.6 + k * 1.6, 8.2, 'feather',
                     ('z', 0.0, [fx, 19.6, 8.2]))
    m.box('eye_block', [4.2, 21.6, 4.6], [11.8, 27.4, 11.4], 'totem_wood', faces={'north': 'totem_eye',
                                                                               'south': 'totem_eye'})
    m.box('brow', [4.0, 27.2, 4.2], [12.0, 28.4, 11.8], 'totem_carving')
    m.box('crown', [5.6, 28.4, 5.6], [10.4, 31.0, 10.4], 'totem_carving', ('y', 45.0, [8, 29.7, 8]))
    plate_ns(m, 'top_feather_a', 6.6, 29.0, 8.4, 32.0, 8.0, 'feather', ('z', 22.5, [8, 29, 8]))
    plate_ns(m, 'top_feather_b', 7.6, 29.0, 9.4, 32.0, 8.0, 'feather', ('z', -22.5, [8, 29, 8]))
    for i, (x, y, z) in enumerate(((4.3, 3.0, 6.0), (11.2, 11.0, 9.0), (6.0, 18.4, 4.3), (9.0, 6.0, 11.3))):
        m.box(f'moss_{i}', [x - 0.6, y, z - 0.6], [x + 1.6, y + 2.2, z + 1.6], 'moss')
    return [m], TOTEM_MATS


