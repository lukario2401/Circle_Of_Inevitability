"""Builds the Observer (Sublunary Eye pathway) ModelFx box models (Java block-model JSON) and their textures.

Run from the repository root (generate.py runs this and everything else):
    python3 tools/model_gen/observer/models.py src/main/resources/assets/circle_of_inevitability
then press F3+T in game. ../hanged_man/render.py draws any of them to a PNG without the game:
    python3 tools/model_gen/hanged_man/render.py src/main/resources/assets/circle_of_inevitability out.png \
        observer/totem observer/pixie_wings_0,observer/pixie_wings_1,observer/pixie_wings_2

Everything goes to models/model_fx/observer/ and textures/model_fx/observer/. Each JSON's "credit" says what it is,
how big, where its pivot is and how to play it; ObserverFx.java plays them all. The framed canvases are made by
paintings.py and the flat pictures (circles, rings, eyes, strings, the Painting World) by pictures.py.

The model writer is the one of ../star_dragon/models.py (same atlas layout, same rules, faces={...} for single faces
in another material), copied here so the Pathways can change without touching each other.

Rotations follow the right-hand rule, as in the other generators:
  axis x: +Y tilts toward +Z for a positive angle (so a box reaching to +Z droops);
  axis z: +Y tilts toward -X (so +X tilts toward +Y: a right wing rises);  axis y: +X turns toward -Z.
Front = north (-Z) for everything that has a front; right = +X.

To add a model: a function returning (models, materials), one line in BUILDERS, a constant in ObserverFx.
"""
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from textures import CELL, atlas  # noqa: E402

NAMESPACE = 'circle_of_inevitability'
FOLDER = 'observer'
ALLOWED = (-45.0, -22.5, 0.0, 22.5, 45.0)
TEX_PX_PER_MODEL_PX = CELL / 16.0          # 2 texture pixels per model pixel
CREDIT = 'Circle Of Inevitability - Observer '
MADE_BY = ' Generated by tools/model_gen/observer.'


class Model:
    def __init__(self, name, credit, materials):
        self.name = FOLDER + '/' + name
        self.credit = CREDIT + credit + MADE_BY
        self.materials = materials
        self.elements = []

    def box(self, name, frm, to, mat, rot=None, full=(), skip=(), faces=None):
        """rot = (axis, angle, origin). full = faces that show their whole cell. skip = faces left out.
        faces = {'up': 'other_material'}: those faces show another material (whole cell)."""
        for m in [mat] + list((faces or {}).values()):
            if m not in self.materials:
                raise ValueError(f'{self.name}: material {m} is not in its atlas')
        frm = [round(v, 4) for v in frm]
        to = [round(v, 4) for v in to]
        for a, b in zip(frm, to):
            if a > b:
                raise ValueError(f'{self.name}/{name}: from > to ({frm} {to})')
            if a < -16 or b > 32:
                raise ValueError(f'{self.name}/{name}: outside -16..32 ({frm} {to})')
        if rot is not None and rot[1] not in ALLOWED:
            raise ValueError(f'{self.name}/{name}: angle {rot[1]}')
        self.elements.append(dict(name=name, frm=frm, to=to, mat=mat, rot=rot, full=tuple(full), skip=tuple(skip),
                                  faces=dict(faces or {})))

    def json(self, cells, tex_w, tex_h):
        out = []
        for e in self.elements:
            (x0, y0, z0), (x1, y1, z1) = e['frm'], e['to']
            sizes = {
                'north': (x1 - x0, y1 - y0), 'south': (x1 - x0, y1 - y0),
                'east': (z1 - z0, y1 - y0), 'west': (z1 - z0, y1 - y0),
                'up': (x1 - x0, z1 - z0), 'down': (x1 - x0, z1 - z0),
            }
            faces = {}
            for face, (w, h) in sizes.items():
                if face in e['skip']:
                    continue
                mat = e['faces'].get(face, e['mat'])
                cx, cy = cells[mat]
                if face in e['full'] or face in e['faces']:
                    pw, ph = CELL, CELL
                else:
                    pw = min(CELL, max(1.0, w * TEX_PX_PER_MODEL_PX))
                    ph = min(CELL, max(1.0, h * TEX_PX_PER_MODEL_PX))
                u0 = cx * CELL / tex_w * 16
                v0 = cy * CELL / tex_h * 16
                faces[face] = {
                    'uv': [round(u0, 4), round(v0, 4), round(u0 + pw / tex_w * 16, 4), round(v0 + ph / tex_h * 16, 4)],
                    'texture': '#0',
                }
            el = {'name': e['name'], 'from': e['frm'], 'to': e['to']}
            # an angle of 0 is still written for frames, so every step of a smooth model has the same cubes alike
            if e['rot'] is not None:
                axis, angle, origin = e['rot']
                el['rotation'] = {'angle': angle, 'axis': axis, 'origin': [round(v, 4) for v in origin]}
            el['faces'] = faces
            out.append(el)
        return out


def save_json(assets, name, data):
    path = os.path.join(assets, 'models/model_fx', name + '.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)


def write(assets, models, tex_name, materials, seed):
    """Writes every model sharing one atlas called tex_name."""
    img, cells = atlas(materials, seed)
    tex_w, tex_h = img.size
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, tex_name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{tex_name}'
    for m in models:
        save_json(assets, m.name, {
            'credit': m.credit,
            'texture_size': [tex_w, tex_h],
            'textures': {'0': tex_id, 'particle': tex_id},
            'elements': m.json(cells, tex_w, tex_h),
        })
    return [m.name for m in models]


# ------------------------------------------------------------------ shapes

def centered(cx, cy, cz, sx, sy, sz):
    return [cx - sx / 2, cy - sy / 2, cz - sz / 2], [cx + sx / 2, cy + sy / 2, cz + sz / 2]


def octagon_y(m, name, cx, cz, y0, y1, width, mat, faces=None, **kw):
    """A round shaft standing up: two square prisms, one turned 45 degrees. faces= go on the first only."""
    m.box(name, [cx - width / 2, y0, cz - width / 2], [cx + width / 2, y1, cz + width / 2], mat, faces=faces, **kw)
    m.box(name + '_t', [cx - width / 2, y0, cz - width / 2], [cx + width / 2, y1, cz + width / 2], mat,
          ('y', 45.0, [cx, (y0 + y1) / 2, cz]), **kw)


def ball(m, name, cx, cy, cz, size, mat):
    """A rough ball: a cube turned three ways."""
    m.box(name, *centered(cx, cy, cz, size, size, size), mat)
    m.box(name + '_y', *centered(cx, cy, cz, size, size, size), mat, ('y', 45.0, [cx, cy, cz]))
    m.box(name + '_x', *centered(cx, cy, cz, size * 0.9, size * 0.9, size * 0.9), mat, ('x', 45.0, [cx, cy, cz]))
    m.box(name + '_z', *centered(cx, cy, cz, size * 0.9, size * 0.9, size * 0.9), mat, ('z', 45.0, [cx, cy, cz]))


def plate_ns(m, name, x0, y0, x1, y1, z, mat, rot=None, back=None):
    """A thin plate standing across z (seen from the front and the back), each face its whole cell."""
    m.box(name, [x0, y0, z - 0.05], [x1, y1, z + 0.05], mat, rot, full=('north', 'south'),
          skip=('up', 'down', 'east', 'west'), faces={'south': back} if back else None)


def plate_ew(m, name, z0, y0, z1, y1, x, mat, rot=None):
    """A thin plate standing across x (seen from the sides)."""
    m.box(name, [x - 0.05, y0, z0], [x + 0.05, y1, z1], mat, rot, full=('east', 'west'),
          skip=('up', 'down', 'north', 'south'))


def plate_ud(m, name, x0, z0, x1, z1, y, mat, rot=None):
    """A thin plate lying flat (seen from above and below)."""
    m.box(name, [x0, y - 0.05, z0], [x1, y + 0.05, z1], mat, rot, full=('up', 'down'),
          skip=('north', 'south', 'east', 'west'))


def humanoid(m, mats, height=32.0, slim=1.0, arm_pitch=(0.0, 0.0), y0=0.0, head=None, eyes=None):
    """A standing figure, feet at y0, 'height' pixels tall (2 blocks = 32), front north.
    mats = dict(body=, limb=, head=, edge=None). arm_pitch = (left, right) x-rotation of the arms (negative raises
    them forward). Returns the shoulder height, for things held in the hands."""
    h = height / 32.0
    leg, torso_h, head_s = 12 * h, 10 * h, 6 * h
    w = slim
    m.box('leg_l', [8 - 3.2 * w, y0, 7], [8 - 0.4 * w, y0 + leg, 9.4], mats['limb'])
    m.box('leg_r', [8 + 0.4 * w, y0, 7], [8 + 3.2 * w, y0 + leg, 9.4], mats['limb'])
    top = y0 + leg + torso_h
    m.box('torso', [8 - 3.8 * w, y0 + leg, 6.6], [8 + 3.8 * w, top, 9.8], mats['body'])
    shoulder = top - 0.6
    for side, sign, pitch in (('l', -1, arm_pitch[0]), ('r', 1, arm_pitch[1])):
        x0 = 8 + sign * 3.9 * w
        xs = sorted([x0, x0 + sign * 2.4 * w])
        m.box(f'arm_{side}', [xs[0], shoulder - 10 * h, 6.9], [xs[1], shoulder, 9.5], mats['limb'],
              ('x', pitch, [sum(xs) / 2, shoulder, 8.2]))
    m.box('head', [8 - head_s / 2, top, 8.2 - head_s / 2], [8 + head_s / 2, top + head_s, 8.2 + head_s / 2],
          head or mats['head'], faces=None)
    if eyes:
        ey = top + head_s * 0.55
        m.box('eye_l', [8 - head_s * 0.36, ey, 8.2 - head_s / 2 - 0.15], [8 - head_s * 0.1, ey + 0.8, 8.2 - head_s / 2],
              eyes)
        m.box('eye_r', [8 + head_s * 0.1, ey, 8.2 - head_s / 2 - 0.15], [8 + head_s * 0.36, ey + 0.8, 8.2 - head_s / 2],
              eyes)
    return shoulder, top


