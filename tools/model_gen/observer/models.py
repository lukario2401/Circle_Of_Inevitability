# 3. Pixie Wings: two pairs of translucent dragonfly wings, three steps of a beat
# =====================================================================================================

WING_MATS = ['wing', 'wing_flip', 'faint_edge']
WING_ANGLES = (22.5, 0.0, -22.5)         # raised, level, down


def _pixie_wings(step):
    m = Model(f'pixie_wings_{step}',
              'Pixie Wings, step ' + str(step) + ' of 3 (raised, level, lowered): two pairs of pale-teal dragonfly '
              'wings, see-through with a net of veins, spreading from the shoulder blades; 2.2 blocks across. Worn '
              'on the back: modelOnTurning at the feet (the wings sit at shoulder height), pivot 8,0,8. Play '
              'ModelFx.of("observer/pixie_wings").frames(3).smooth() and key the beat. .glow().unshaded().seeThrough()',
              WING_MATS)
    angle = WING_ANGLES[step]
    for side, sign in (('r', 1), ('l', -1)):
        root = 8 + sign * 1.2
        mat = 'wing' if sign > 0 else 'wing_flip'
        x0, x1 = sorted([root, root + sign * 17.5])
        plate_ns(m, f'upper_{side}', x0, 21.0, x1, 27.0, 10.2, mat, ('z', angle * sign, [root, 23.0, 10.2]))
        x0, x1 = sorted([root, root + sign * 14.0])
        plate_ns(m, f'lower_{side}', x0, 16.0, x1, 21.0, 10.4, mat, ('z', (angle - 22.5) * sign, [root, 20.0, 10.4]))
    m.box('root', [6.6, 18.0, 9.8], [9.4, 24.0, 10.6], 'faint_edge')
    return m


def pixie_wings():
    return [_pixie_wings(s) for s in range(3)], WING_MATS


