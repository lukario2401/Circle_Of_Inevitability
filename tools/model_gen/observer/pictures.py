def dissonance_ring(assets):
    size = 256
    img, d = blank(size * 2)
    c = size
    rnd = random.Random(15)
    for k in range(5):                                                       # the stave, broken into shards
        r = 190 + k * 12
        a = 0.0
        while a < math.tau:
            span = rnd.uniform(0.2, 0.6)
            off = rnd.uniform(-10, 10)
            d.arc([c - r - off, c - r - off, c + r + off, c + r + off], math.degrees(a), math.degrees(a + span),
                  fill=SOFT, width=3)
            a += span + rnd.uniform(0.05, 0.25)
    for k in range(10):                                                      # notes knocked askew
        a = rnd.uniform(0, math.tau)
        r = rnd.uniform(120, 240)
        x, y = c + math.cos(a) * r, c + math.sin(a) * r
        t = rnd.uniform(-0.8, 0.8)
        d.ellipse([x - 9, y - 7, x + 9, y + 7], fill=WHITE)
        d.line([(x + 8, y), (x + 8 + math.sin(t) * 34, y - math.cos(t) * 34)], fill=WHITE, width=4)
    for k in range(3):                                                       # snapped strings, curling
        y = c - 40 + k * 40
        d.line([(c - 150, y), (c - 20, y + 6), (c - 4, y + 30)], fill=WHITE, width=3)
        d.line([(c + 150, y), (c + 24, y - 4), (c + 8, y - 26)], fill=WHITE, width=3)
    return write_picture_model(assets, 'dissonance_ring',
                               'Dissonance: the same stave broken into shards, notes knocked askew, the strings '
                               'snapped and curling; 1 block wide, lying flat. White: tint it a sour violet. Pivot '
                               '8,0,8. .glow().unshaded().seeThrough()', FLAT, smooth(img, size))


