def foregone_script(assets):
    size = 256
    img, d = blank(size * 2)
    c = size
    rnd = random.Random(16)
    ring(d, c, 248, WHITE, 6)
    ring(d, c, 196, SOFT, 3)
    for band, (r0, r1) in enumerate(((204, 240), (120, 186))):              # two bands of writing
        a = 0.0
        while a < math.tau - 0.05:
            word = rnd.uniform(0.06, 0.16)
            rr = (r0 + r1) / 2
            for i in range(int(word * 60)):
                t = a + word * i / max(1, int(word * 60))
                h = rnd.uniform(-1, 1) * (r1 - r0) * 0.35
                d.point((c + math.cos(t) * (rr + h), c + math.sin(t) * (rr + h)), fill=WHITE)
                d.line([(c + math.cos(t) * (rr + h), c + math.sin(t) * (rr + h)),
                        (c + math.cos(t + 0.01) * (rr - h * 0.6), c + math.sin(t + 0.01) * (rr - h * 0.6))],
                       fill=WHITE, width=3)
            a += word + 0.04
    d.line([(c - 70, c + 60), (c + 70, c - 60)], fill=WHITE, width=10)        # the final stroke of the quill
    d.ellipse([c + 62, c - 68, c + 78, c - 52], fill=WHITE)
