def dimensional_rift(assets):
    size, frames = 64, 4
    out = []
    for f in range(frames):
        img, d = blank(size * 2)
        w = size * 2
        rnd = random.Random(12)
        pts_l, pts_r = [], []
        for y in range(0, w + 1, 8):
            open_ = math.sin(y / w * math.pi) ** 0.8
            jag = rnd.uniform(-5, 5)
            pts_l.append((w / 2 - 26 * open_ + jag, y))
            pts_r.append((w / 2 + 26 * open_ + jag, y))
        d.polygon(pts_l + pts_r[::-1], fill=(10, 6, 24, 245))
        for k in range(6):                                                    # straight lines of the higher space
            y = (k * 23 + f * 6) % w
            d.line([(w / 2 - 18, y), (w / 2 + 18, y + 10)], fill=(140, 120, 255, 150), width=2)
        d.line(pts_l, fill=(216, 204, 255, 255), width=4)
        d.line(pts_r, fill=(216, 204, 255, 255), width=4)
        out.append(smooth(img, size))
    return write_picture_model(assets, 'dimensional_rift',
                               'Dimensional Passage: a tall jagged tear in the world, black-violet inside with '
                               'straight lines of a higher space sliding through it, its edges bright (animated); 1 '
                               'block, standing. Its own colors. Pivot 8,0,8 = its foot. Scale it to 1.2 x 2.4. '
                               '.glow().unshaded().seeThrough()', STANDING, animated(out, size), frames, 2)


