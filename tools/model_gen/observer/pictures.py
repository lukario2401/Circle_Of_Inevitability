def world_barrier(assets):
    size, frames = 64, 4
    out = []
    for f in range(frames):
        img, d = blank(size * 2)
        w = size * 2
        px = img.load()
        for y in range(w):
            for x in range(w):
                v = 0.5 + 0.5 * math.sin(x * 0.18 + y * 0.05 + f * math.pi / 2) * math.sin(y * 0.11 - f * math.pi / 2)
                bottom = min(1.0, (w - y) / (w * 0.2))
                top = min(1.0, y / (w * 0.5))
                a = int(170 * v * bottom * top)
                px[x, y] = (255, 255, 255, a)
        out.append(smooth(img, size))
    return write_picture_model(assets, 'world_barrier',
                               'The Painting World\'s formless barrier: a wall of moving shimmer round a circle, '
                               'brightest near the ground and fading upward (animated); a ring of 8 plates, 1 block '
                               'across and 1 high at scale 1, seen from inside and out. White: tint it the Pathway\'s '
                               'violet. Pivot 8,0,8. .scale(2r, height, 2r). .glow().unshaded().seeThrough()',
                               ring_of_plates(8.0, 16.0), animated(out, size), frames, 4)


