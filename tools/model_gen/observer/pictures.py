def territory_circle(assets):
    size = 256
    img, d = blank(size * 2)
    c = size
    rnd = random.Random(21)
    brush_ring(d, c, 246, 12, WHITE, rnd)
    brush_ring(d, c, 222, 5, SOFT, rnd, gaps=8)
    for k in range(16):                                                       # carved totem glyphs round the ring
        a = math.tau * k / 16
        x, y = c + math.cos(a) * 196, c + math.sin(a) * 196
        if k % 4 == 0:
            eye_shape(d, x, y, 14, 7, None, WHITE, 3)
            d.ellipse([x - 3, y - 3, x + 3, y + 3], fill=WHITE)
        elif k % 2 == 0:
            d.polygon([(x, y - 12), (x + 9, y + 8), (x - 9, y + 8)], outline=SOFT, width=3)
        else:
            d.line([(x - 8, y - 8), (x + 8, y + 8)], fill=SOFT, width=3)
            d.line([(x - 8, y + 8), (x + 8, y - 8)], fill=SOFT, width=3)
    for k in range(4):                                                       # four roots toward the middle
        a = math.tau * k / 4 + math.pi / 4
        pts = [(c + math.cos(a + math.sin(t * 3) * 0.08) * (170 - t * 110), c + math.sin(a + math.sin(t * 3) * 0.08) *
                (170 - t * 110)) for t in [i / 10 for i in range(11)]]
        d.line(pts, fill=FAINT, width=4)
    brush_ring(d, c, 60, 6, SOFT, rnd)
    return write_picture_model(assets, 'territory_circle',
                               'Totem Territory\'s ground: a ring brushed in one stroke, a broken ring inside it, '
                               'sixteen carved glyphs (eyes, triangles, crosses) and four roots reaching for the '
                               'totem; 1 block wide, lying flat. White: tint it moss green or earth brown. Pivot '
                               '8,0,8. Scale it to the Territory\'s width. .glow().unshaded().seeThrough()',
                               FLAT, smooth(img, size))


