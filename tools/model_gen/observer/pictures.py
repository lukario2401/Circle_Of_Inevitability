def observation_eye(assets):
    size = 64
    img, d = blank(size * 2)
    c = size
    lids = eye_shape(d, c, c, 56, 30, None, WHITE, 7)
    iris(img, c, c, 18, SOFT, (0, 0, 0, 0), lids)
    d.ellipse([c - 6, c - 6, c + 6, c + 6], fill=WHITE)
    for k in range(5):                                                       # lashes
        a = math.pi + math.pi * (k + 0.5) / 5
        d.line([(c + math.cos(a) * 46, c + math.sin(a) * 30), (c + math.cos(a) * 60, c + math.sin(a) * 48)],
               fill=SOFT, width=4)
    return write_picture_model(assets, 'observation_eye',
                               'Observation: a small eye with lashes and a bright pupil, on two crossed planes so it '
                               'reads from every side; 1 block at scale 1 (play it at 0.35 over the head, one per '
                               'level: SpellFx.overHead or ObserverFx.observed). White: tint it per level (pale, '
                               'teal, violet). Pivot 8,8,8. .glow().unshaded().seeThrough()',
                               CROSSED, smooth(img, size))


