"""The Observer's picture models: models whose faces each show one whole picture (a circle on the ground, an eye over
a head, a string, a tear in space, the Painting World's barrier and sky). Run by generate.py; on its own:
    python3 tools/model_gen/observer/pictures.py src/main/resources/assets/circle_of_inevitability

White pictures take any tint with .color(...); the ones that keep their own colors say so in their credit.
Each picture is drawn at twice its size and brought down, for soft edges.

To add one: a function (assets) -> model name(s) that calls write_picture_model, and its name in PICTURES.
"""
import json
import math
import os
import random
import sys

from PIL import Image, ImageDraw

NAMESPACE = 'circle_of_inevitability'
FOLDER = 'observer'
ALLOWED = (-45.0, -22.5, 0.0, 22.5, 45.0)
CREDIT = 'Circle Of Inevitability - Observer '
MADE_BY = ' Generated by tools/model_gen/observer.'

WHITE = (255, 255, 255, 255)
SOFT = (255, 255, 255, 160)
FAINT = (255, 255, 255, 80)

FLAT = [('plate', [0, 0, 0], [16, 0, 16], ['up', 'down'])]
STANDING = [('plate', [0, 0, 8], [16, 16, 8], ['north', 'south'])]
CROSSED = [('a', [0, 0, 8], [16, 16, 8], ['north', 'south']),
           ('b', [8, 0, 0], [8, 16, 16], ['east', 'west'])]


def ring_of_plates(radius=8.0, height=16.0):
    """A ring of 8 standing plates seen from inside and outside: a wall round a circle 2*radius pixels across.
    A plate north of the middle turned 0 / 45 / -45 around the middle gives three of them, the same south gives three
    more, and one east and one west close it."""
    side = 2 * radius * math.tan(math.pi / 8) + 0.1
    mid = [8, height / 2, 8]
    els = []
    for name, z in (('n', 8 - radius), ('s', 8 + radius)):
        for turn in (0.0, 45.0, -45.0):
            els.append((f'{name}{turn:+.0f}', [8 - side / 2, 0, z], [8 + side / 2, height, z], ['north', 'south'],
                        ('y', turn, mid)))
    for name, x in (('e', 8 + radius), ('w', 8 - radius)):
        els.append((name, [x, 0, 8 - side / 2], [x, height, 8 + side / 2], ['east', 'west']))
    return els


def save_json(assets, name, data):
    path = os.path.join(assets, 'models/model_fx', name + '.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)


def write_picture_model(assets, name, credit, elements, img, frames=1, frametime=3, tex_name=None):
    """A model whose every face shows the whole of one picture. frames > 1: img holds the frames stacked downward
    (an animated texture). tex_name: the picture's file name when it differs from the model's."""
    tex_name = tex_name or name
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, tex_name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    meta = tex_path + '.mcmeta'
    if frames > 1:
        with open(meta, 'w') as f:
            json.dump({'animation': {'frametime': frametime, 'interpolate': True}}, f)
    elif os.path.exists(meta):
        os.remove(meta)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{tex_name}'
    els = []
    for el in elements:
        el_name, frm, to, faces = el[:4]
        out = {'name': el_name, 'from': [round(v, 4) for v in frm], 'to': [round(v, 4) for v in to], 'shade': False}
        if len(el) > 4 and el[4] is not None and el[4][1] != 0.0:
            axis, angle, origin = el[4]
            if angle not in ALLOWED:
                raise ValueError(f'{name}/{el_name}: angle {angle}')
            out['rotation'] = {'angle': angle, 'axis': axis, 'origin': [round(v, 4) for v in origin]}
        out['faces'] = {face: {'uv': [0, 0, 16, 16], 'texture': '#0'} for face in faces}
        els.append(out)
    w = img.size[0]
    save_json(assets, FOLDER + '/' + name, {
        'credit': CREDIT + credit + MADE_BY,
        'texture_size': [w, w], 'textures': {'0': tex_id, 'particle': tex_id}, 'elements': els})
    return FOLDER + '/' + name


def blank(size):
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def smooth(img, size):
    return img.resize((size, size), Image.LANCZOS)


def animated(frames_list, size):
    img = Image.new('RGBA', (size, size * len(frames_list)), (0, 0, 0, 0))
    for i, f in enumerate(frames_list):
        img.paste(f, (0, i * size))
    return img


def ring(d, c, r, fill, width, cy=None):
    cy = c if cy is None else cy
    d.ellipse([c - r, cy - r, c + r, cy + r], outline=fill, width=width)


def glow_dot(d, x, y, r, alpha=255, color=(255, 255, 255)):
    for k in range(3, 0, -1):
        rr = r * (1 + k * 0.6)
        d.ellipse([x - rr, y - rr, x + rr, y + rr], fill=color + (int(alpha * 0.18 * (4 - k) / 3),))
    d.ellipse([x - r, y - r, x + r, y + r], fill=color + (alpha,))


def disc_mask(img, margin=1):
    size = img.size[0]
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).ellipse([margin, margin, size - 1 - margin, size - 1 - margin], fill=255)
    cut = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    cut.paste(img, (0, 0), mask)
    return cut


def brush_ring(d, c, r, width, color, rnd, gaps=0, wobble=0.04):
    """A circle painted in one stroke: thick and thin, a little uneven, maybe with gaps where the brush lifted."""
    steps = 180
    for i in range(steps):
        t0, t1 = i / steps, (i + 1) / steps
        if gaps and int(t0 * gaps * 2) % 2 == 1 and rnd.random() < 0.9:
            continue
        rr = r * (1 + wobble * math.sin(t0 * math.tau * 3 + 1.3))
        w = width * (0.55 + 0.45 * math.sin(t0 * math.pi * 2 + 0.6) ** 2)
        a0, a1 = t0 * math.tau, t1 * math.tau
        d.line([(c + math.cos(a0) * rr, c + math.sin(a0) * rr), (c + math.cos(a1) * rr, c + math.sin(a1) * rr)],
               fill=color, width=max(1, int(w)))


def eye_shape(d, c, cy, half_w, half_h, fill=None, outline=WHITE, width=6, open_=1.0):
    """An almond eye, 'open_' from 0 (shut, a line) to 1."""
    hh = half_h * open_
    top = [(c - half_w + i * 2 * half_w / 32, cy - math.sin(i / 32 * math.pi) * hh) for i in range(33)]
    low = [(c + half_w - i * 2 * half_w / 32, cy + math.sin(i / 32 * math.pi) * hh) for i in range(33)]
    if fill:
        d.polygon(top + low, fill=fill)
    d.line(top, fill=outline, width=width)
    d.line(low, fill=outline, width=width)
    return top + low


def iris(img, c, cy, r, color, pupil=(0, 0, 0, 0), clip=None):
    layer, d = blank(img.size[0])
    d.ellipse([c - r, cy - r, c + r, cy + r], fill=color)
    d.ellipse([c - r * 0.42, cy - r * 0.42, c + r * 0.42, cy + r * 0.42], fill=pupil)
    if clip is not None:
        mask = Image.new('L', img.size, 0)
        ImageDraw.Draw(mask).polygon(clip, fill=255)
        cut = Image.new('RGBA', img.size, (0, 0, 0, 0))
        cut.paste(layer, (0, 0), mask)
        layer = cut
    img.alpha_composite(layer)


