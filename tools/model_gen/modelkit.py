"""
Small helpers for writing ModelFx models (Blockbench "Java Block/Item" JSON) and their textures from Python.

    from modelkit import Texture, Model
    tex = Texture("conqueror/powder_keg", 64, 64)          # textures/model_fx/conqueror/powder_keg.png
    tex.zone("wood", 0, 0, 8, 8, wood_painter)            # a part of the texture, in uv units (0..16 = all of it)
    m = Model("conqueror/powder_keg", tex, "credit line")
    m.cube("body", (4, 0, 4), (12, 11, 12), "wood")       # pixels; every face shows the whole "wood" zone
    m.cube("fuse", ..., "fuse", rot=(22.5, "z", (8, 11.5, 8)))
    m.save(assets_root); tex.save(assets_root)

A painter is fn(tx, ty, x, y, frame) -> (r, g, b, a): tx/ty run 0..1 across the zone, x/y are pixels, frame is
the animation frame (Texture(..., frames=4) stacks 4 frames and writes a .png.mcmeta).
"""
import json, math, os, random

from PIL import Image


def lerp(a, b, t):
    t = max(0.0, min(1.0, t))
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(len(a)))


def ramp(stops, t):
    """stops = [(0.0, color), (0.4, color), (1.0, color)]: the color at t."""
    t = max(0.0, min(1.0, t))
    for (t0, c0), (t1, c1) in zip(stops, stops[1:]):
        if t <= t1:
            return lerp(c0, c1, (t - t0) / max(1e-6, t1 - t0))
    return stops[-1][1]


class Texture:
    def __init__(self, name, width, height, frames=1, frametime=2, interpolate=True, seed=1):
        self.name, self.w, self.h, self.frames = name, width, height, frames
        self.frametime, self.interpolate = frametime, interpolate
        self.img = Image.new("RGBA", (width, height * frames), (0, 0, 0, 0))
        self.zones = {}
        self.rng = random.Random(seed)

    def zone(self, name, u0, v0, u1, v1, painter=None):
        self.zones[name] = [u0, v0, u1, v1]
        if painter:
            px = self.img.load()
            x0, x1 = int(round(u0 * self.w / 16)), int(round(u1 * self.w / 16))
            y0, y1 = int(round(v0 * self.h / 16)), int(round(v1 * self.h / 16))
            for f in range(self.frames):
                for y in range(y0, y1):
                    for x in range(x0, x1):
                        tx = (x - x0 + 0.5) / (x1 - x0)
                        ty = (y - y0 + 0.5) / (y1 - y0)
                        px[x, y + f * self.h] = tuple(painter(tx, ty, x - x0, y - y0, f))
        return self.zones[name]

    def uv(self, name, flip_u=False, flip_v=False):
        u0, v0, u1, v1 = self.zones[name]
        if flip_u: u0, u1 = u1, u0
        if flip_v: v0, v1 = v1, v0
        return [u0, v0, u1, v1]

    def id(self):
        return "circle_of_inevitability:model_fx/" + self.name

    def save(self, root):
        path = os.path.join(root, "textures/model_fx", self.name + ".png")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        self.img.save(path)
        meta = path + ".mcmeta"
        if self.frames > 1:
            with open(meta, "w") as f:
                json.dump({"animation": {"frametime": self.frametime, "interpolate": self.interpolate}}, f)
        elif os.path.exists(meta):
            os.remove(meta)


FACES = ("north", "south", "east", "west", "up", "down")


class Model:
    def __init__(self, name, texture, credit):
        self.name, self.tex, self.credit = name, texture, credit
        self.elements = []

    def cube(self, name, frm, to, zone, rot=None, faces=None, skip=()):
        """zone: the zone every face shows; faces: {"north": "other_zone" or [uv], ...} to change some."""
        out = {}
        for face in FACES:
            if face in skip:
                continue
            z = (faces or {}).get(face, zone)
            uv = z if isinstance(z, list) else self.tex.uv(z)
            out[face] = {"uv": [round(v, 4) for v in uv], "texture": "#0"}
        e = {"name": name, "from": [round(v, 4) for v in frm], "to": [round(v, 4) for v in to], "faces": out}
        if rot:
            angle, axis, origin = rot
            e["rotation"] = {"angle": angle, "axis": axis, "origin": [round(v, 4) for v in origin]}
        self.elements.append(e)
        return e

    def json(self):
        return {"credit": "Circle Of Inevitability - " + self.credit + " Generated by tools/model_gen.",
                "texture_size": [self.tex.w, self.tex.h],
                "textures": {"0": self.tex.id(), "particle": self.tex.id()},
                "elements": self.elements}

    def save(self, root, suffix=""):
        path = os.path.join(root, "models/model_fx", self.name + suffix + ".json")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            json.dump(self.json(), f, indent=1)
        return path


def rotate2(px, py, ox, oy, degrees):
    """(px, py) turned around (ox, oy) by degrees, counter-clockwise (right-handed)."""
    a = math.radians(degrees)
    dx, dy = px - ox, py - oy
    return ox + dx * math.cos(a) - dy * math.sin(a), oy + dx * math.sin(a) + dy * math.cos(a)
