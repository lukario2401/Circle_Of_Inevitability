def _chain(name, credit, link, extra, end):
    """Nine links standing up from y -16, each one turned a quarter to the last, and a different end at the top."""
    mats = [link, extra]
    m = Model(name, credit, mats)
    for i in range(9):
        y0 = -16 + i * 5
        if i % 2 == 0:                                                       # a link in the x-y plane
            m.box(f'link{i}_w', [6, y0 + 1, 7.5], [7, y0 + 5, 8.5], link)
            m.box(f'link{i}_e', [9, y0 + 1, 7.5], [10, y0 + 5, 8.5], link)
            m.box(f'link{i}_top', [6, y0 + 5, 7.5], [10, y0 + 6, 8.5], link)
            m.box(f'link{i}_low', [6, y0, 7.5], [10, y0 + 1, 8.5], link)
        else:                                                                # turned: in the z-y plane
            m.box(f'link{i}_n', [7.5, y0 + 1, 6], [8.5, y0 + 5, 7], link)
            m.box(f'link{i}_s', [7.5, y0 + 1, 9], [8.5, y0 + 5, 10], link)
            m.box(f'link{i}_top', [7.5, y0 + 5, 6], [8.5, y0 + 6, 10], link)
            m.box(f'link{i}_low', [7.5, y0, 6], [8.5, y0 + 1, 10], link)
    end(m, extra, link)
    return m


def _blood_end(m, drip, link):
    """A barbed hook of blood at the top, and drops hanging off the links."""
    m.box('hook_shaft', [7.4, 29.5, 7.4], [8.6, 32, 8.6], link)
    m.box('barb_w', [5.4, 28.6, 7.6], [7.4, 29.6, 8.4], link, ('z', -45.0, [7.4, 29.6, 8]))
    m.box('barb_e', [8.6, 28.6, 7.6], [10.6, 29.6, 8.4], link, ('z', 45.0, [8.6, 29.6, 8]))
    for i, (x, y) in enumerate(((6.0, -6.0), (9.6, 3.5), (6.2, 13.0), (9.8, 21.0), (6.1, -13.5))):
        m.box(f'drip{i}', [x - 0.35, y - 1.6, 7.65], [x + 0.35, y, 8.35], drip)


