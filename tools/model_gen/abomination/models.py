# 4. Raise the Dead: a rotting hand clawing out of the ground, 3 steps
# =====================================================================================================

def segment(m, name, start, length, angle, x0, x1, thick, mat):
    """A finger bone from start = (y, z), 'angle' degrees from straight up curling toward -z (the palm side):
    0 = up, -90 = forward. Any multiple of 22.5 from 0 to -180. Returns its far end (y, z)."""
    sy, sz = start
    base = min((0.0, -90.0, -180.0), key=lambda b: abs(angle - b))
    r = angle - base
    if base == 0.0:
        frm, to = [x0, sy, sz - thick / 2], [x1, sy + length, sz + thick / 2]
    elif base == -90.0:
        frm, to = [x0, sy - thick / 2, sz - length], [x1, sy + thick / 2, sz]
    else:
        frm, to = [x0, sy - length, sz - thick / 2], [x1, sy, sz + thick / 2]
    m.box(name, frm, to, mat, ('x', r, [(x0 + x1) / 2, sy, sz]))
    a = math.radians(angle)
    return sy + math.cos(a) * length, sz + math.sin(a) * length


