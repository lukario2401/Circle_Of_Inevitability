def _glyphs(d, c, radius, count, fill, seed, size=4):
    """Small angular runes round a circle."""
    rnd = random.Random(seed)
    for i in range(count):
        a = math.tau * (i + 0.5) / count
        x, y = c + math.cos(a) * radius, c + math.sin(a) * radius
        s = size
        k = rnd.randrange(4)
        if k == 0:
            d.line([(x - s, y - s), (x + s, y + s)], fill=fill)
            d.line([(x - s, y + s), (x + s, y - s)], fill=fill)
        elif k == 1:
            d.line([(x, y - s), (x, y + s)], fill=fill)
            d.arc([x - s, y - s, x + s, y + s], 270, 450, fill=fill)
        elif k == 2:
            d.polygon([(x, y - s), (x + s, y), (x, y + s), (x - s, y)], outline=fill)
        else:
            d.line([(x - s, y + s), (x, y - s), (x + s, y + s)], fill=fill)
            d.point((x, y + s * 0.4), fill=fill)


def _chain_links(d, points, fill, width=2, link=7):
    """Chain links drawn along a polyline: ovals along it, every other one seen edge on."""
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        length = math.hypot(x1 - x0, y1 - y0)
        count = max(1, int(length / link))
        ux, uy = (x1 - x0) / length, (y1 - y0) / length
        for k in range(count):
            cx = x0 + ux * (k + 0.5) * length / count
            cy = y0 + uy * (k + 0.5) * length / count
            half = link * 0.6
            w = 2.6 if k % 2 == 0 else 0.6
            pts = [(cx + ux * half * math.cos(t) - uy * w * math.sin(t), cy + uy * half * math.cos(t) + ux * w * math.sin(t))
                   for t in [i * math.tau / 12 for i in range(13)]]
            d.line(pts, fill=fill, width=width if k % 2 == 0 else max(1, width))


def _thorn(d, x, y, angle, length, width, fill):
    a = angle
    d.polygon([(x + math.cos(a + 1.57) * width, y + math.sin(a + 1.57) * width),
               (x + math.cos(a) * length, y + math.sin(a) * length),
               (x + math.cos(a - 1.57) * width, y + math.sin(a - 1.57) * width)], fill=fill)


