"""Builds the Abomination (Chained pathway) ModelFx models (Java block-model JSON) and their textures.

Run from the repository root:
    python3 tools/model_gen/abomination/models.py src/main/resources/assets/circle_of_inevitability
then press F3+T in game. ../hanged_man/render.py draws any of them to a PNG without the game:
    python3 tools/model_gen/hanged_man/render.py src/main/resources/assets/circle_of_inevitability out.png \
        abomination/doll_vessel abomination/coffin_0,abomination/coffin_1,abomination/coffin_2,abomination/coffin_3

Everything goes to models/model_fx/abomination/ and textures/model_fx/abomination/. Each JSON's "credit" says what
it is, how big, where its pivot is and how to play it; AbominationFx.java plays them all.

Rotations follow the right-hand rule, as in the Hand Of God, Beauty Goddess and Hanged Man generators:
  axis x: +Y tilts toward +Z for a positive angle;  axis z: +Y tilts toward -X (so +X tilts toward +Y);
  axis y: +X turns toward -Z.
"""
import json
import math
import os
import random
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from textures import CELL, atlas  # noqa: E402

NAMESPACE = 'circle_of_inevitability'
FOLDER = 'abomination'
ALLOWED = (-45.0, -22.5, 0.0, 22.5, 45.0)
TEX_PX_PER_MODEL_PX = CELL / 16.0          # 2 texture pixels per model pixel
CREDIT = 'Circle Of Inevitability - Abomination '
MADE_BY = ' Generated by tools/model_gen/abomination.'
SIDES = ('north', 'south', 'east', 'west')


class Model:
    def __init__(self, name, credit, materials):
        self.name = FOLDER + '/' + name
        self.credit = CREDIT + credit + MADE_BY
        self.materials = materials
        self.elements = []

    def box(self, name, frm, to, mat, rot=None, full=(), skip=()):
        """rot = (axis, angle, origin). full = faces that show their whole cell. skip = faces left out."""
        if mat not in self.materials:
            raise ValueError(f'{self.name}: material {mat} is not in its atlas')
        frm = [round(v, 4) for v in frm]
        to = [round(v, 4) for v in to]
        for a, b in zip(frm, to):
            if a > b:
                raise ValueError(f'{self.name}/{name}: from > to ({frm} {to})')
            if a < -16 or b > 32:
                raise ValueError(f'{self.name}/{name}: outside -16..32 ({frm} {to})')
        if rot is not None:
            if rot[1] not in ALLOWED:
                raise ValueError(f'{self.name}/{name}: angle {rot[1]}')
            if rot[1] == 0.0:
                rot = None
        self.elements.append(dict(name=name, frm=frm, to=to, mat=mat, rot=rot, full=tuple(full), skip=tuple(skip)))

    def json(self, cells, tex_w, tex_h):
        out = []
        for e in self.elements:
            cx, cy = cells[e['mat']]
            (x0, y0, z0), (x1, y1, z1) = e['frm'], e['to']
            sizes = {
                'north': (x1 - x0, y1 - y0), 'south': (x1 - x0, y1 - y0),
                'east': (z1 - z0, y1 - y0), 'west': (z1 - z0, y1 - y0),
                'up': (x1 - x0, z1 - z0), 'down': (x1 - x0, z1 - z0),
            }
            faces = {}
            for face, (w, h) in sizes.items():
                if face in e['skip']:
                    continue
                if face in e['full']:
                    pw, ph = CELL, CELL
                else:
                    pw = min(CELL, max(1.0, w * TEX_PX_PER_MODEL_PX))
                    ph = min(CELL, max(1.0, h * TEX_PX_PER_MODEL_PX))
                u0 = cx * CELL / tex_w * 16
                v0 = cy * CELL / tex_h * 16
                faces[face] = {
                    'uv': [round(u0, 4), round(v0, 4), round(u0 + pw / tex_w * 16, 4), round(v0 + ph / tex_h * 16, 4)],
                    'texture': '#0',
                }
            el = {'name': e['name'], 'from': e['frm'], 'to': e['to']}
            if e['rot'] is not None:
                axis, angle, origin = e['rot']
                el['rotation'] = {'angle': angle, 'axis': axis, 'origin': [round(v, 4) for v in origin]}
            el['faces'] = faces
            out.append(el)
        return out


def save_json(assets, name, data):
    path = os.path.join(assets, 'models/model_fx', name + '.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)


def write(assets, models, tex_name, materials, seed):
    """Writes every model (several = the frames of one) sharing one atlas called tex_name."""
    img, cells = atlas(materials, seed)
    tex_w, tex_h = img.size
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, tex_name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{tex_name}'
    for m in models:
        save_json(assets, m.name, {
            'credit': m.credit,
            'texture_size': [tex_w, tex_h],
            'textures': {'0': tex_id, 'particle': tex_id},
            'elements': m.json(cells, tex_w, tex_h),
        })
    return [m.name for m in models]


def write_picture_model(assets, name, credit, elements, img, frames=1, frametime=3):
    """A model whose every face shows the whole of one picture (a flat seal, a standing mark, a tile).
    elements: [(name, from, to, faces)]; frames > 1: img holds the frames stacked downward (an animated texture)."""
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    meta = tex_path + '.mcmeta'
    if frames > 1:
        with open(meta, 'w') as f:
            json.dump({'animation': {'frametime': frametime, 'interpolate': True}}, f)
    elif os.path.exists(meta):
        os.remove(meta)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{name}'
    els = []
    for el in elements:
        el_name, frm, to, faces = el[:4]
        out = {'name': el_name, 'from': [round(v, 4) for v in frm], 'to': [round(v, 4) for v in to], 'shade': False}
        out['faces'] = {face: {'uv': [0, 0, 16, 16], 'texture': '#0'} for face in faces}
        els.append(out)
    w = img.size[0]
    save_json(assets, FOLDER + '/' + name, {
        'credit': CREDIT + credit + MADE_BY,
        'texture_size': [w, w], 'textures': {'0': tex_id, 'particle': tex_id}, 'elements': els})
    return FOLDER + '/' + name


def centered(cx, cy, cz, sx, sy, sz):
    return [cx - sx / 2, cy - sy / 2, cz - sz / 2], [cx + sx / 2, cy + sy / 2, cz + sz / 2]


def ring(m, name, y0, y1, x0, x1, z0, z1, mat, t=0.6, rot=None, full=SIDES):
    """A hollow band round a box (front, back and both sides), t thick: a chain or bandage wound round a body."""
    m.box(name + '_n', [x0, y0, z0 - t], [x1, y1, z0], mat, rot, full=full, skip=('up', 'down'))
    m.box(name + '_s', [x0, y0, z1], [x1, y1, z1 + t], mat, rot, full=full, skip=('up', 'down'))
    m.box(name + '_w', [x0 - t, y0, z0 - t], [x0, y1, z1 + t], mat, rot, full=full, skip=('up', 'down'))
    m.box(name + '_e', [x1, y0, z0 - t], [x1 + t, y1, z1 + t], mat, rot, full=full, skip=('up', 'down'))


def stalk(m, name, base, length, thick, axis, angle, mat):
    """A straight piece (a vine, a stem) standing on 'base', tilted 'angle' about 'axis' round its own foot.
    Returns where its top ends up, so the next piece can stand on it."""
    bx, by, bz = base
    m.box(name, [bx - thick / 2, by, bz - thick / 2], [bx + thick / 2, by + length, bz + thick / 2], mat,
          (axis, angle, [bx, by, bz]))
    a = math.radians(angle)
    if axis == 'z':
        return bx - math.sin(a) * length, by + math.cos(a) * length, bz
    return bx, by + math.cos(a) * length, bz + math.sin(a) * length


def thorn_on(m, name, at, size, axis, angle, mat='thorn'):
    """A small thorn sticking out of a vine at 'at', leaning 'angle' (45 or -45) about 'axis'."""
    x, y, z = at
    w = size * 0.35
    m.box(name, [x - w / 2, y, z - w / 2], [x + w / 2, y + size, z + w / 2], mat, (axis, angle, [x, y, z]))


