HINGE_X, HINGE_Z = 1.0, 4.0


def _lid_box(m, angle, name, frm, to, mat, full=()):
    """A piece of the lid; the lid turns on its left edge (x 1, z 4). angle 90 lays it sideways by hand, since block
    models only turn 45 at most: x and z swap round the hinge and its front faces west."""
    if angle == 90.0:
        (x0, y0, z0), (x1, y1, z1) = frm, to
        nfrm = [HINGE_X + (z0 - HINGE_Z), y0, HINGE_Z - (x1 - HINGE_X)]
        nto = [HINGE_X + (z1 - HINGE_Z), y1, HINGE_Z - (x0 - HINGE_X)]
        nfull = tuple({'north': 'west', 'south': 'east'}.get(f, f) for f in full)
        m.box(name, nfrm, nto, mat, full=nfull)
    else:
        m.box(name, frm, to, mat, ('y', angle, [HINGE_X, 0, HINGE_Z]), full=full)


