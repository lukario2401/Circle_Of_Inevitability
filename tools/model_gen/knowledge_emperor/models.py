def data_stream(assets):
    """A panel of information: columns of glyphs streaming downward (8 frames, each a step further)."""
    size, frames = 64, 8
    img = Image.new('RGBA', (size, size * frames), (0, 0, 0, 0))
    rnd = random.Random(23)
    columns = []
    for x in range(3, size - 3, 7):
        speed = rnd.choice((1, 1, 2))
        glyphs = [(rnd.randrange(9), rnd.randrange(80, 256)) for _ in range(8)]
        columns.append((x, speed, rnd.randrange(32), glyphs))
    for f in range(frames):
        frame, d = _blank(size * 4)
        for x, speed, offset, glyphs in columns:
            for j, (k, a) in enumerate(glyphs):
                # 8 glyphs 32 apart fill the panel; each frame moves the column a whole panel / 8 (x speed),
                # so the last frame runs on into the first without a jump
                y = (offset + j * 32 + f * speed * 32) % (size * 4)
                head = j == (f * speed) % len(glyphs)
                for wrap in (0, -size * 4):
                    _glyph(d, x * 4 + 2, y + wrap, 9, k, (255, 255, 255, 255 if head else a), 3)
        frame = frame.resize((size, size), Image.LANCZOS)
        img.paste(frame, (0, f * size))
    return write_picture_model(assets, 'data_stream',
                               'A panel of information: columns of ancient symbols streaming downward (animated), 1 '
                               'block square, standing (it faces north and south). White and see-through: tint it '
                               'indigo or orchid. Pivot 8,0,8 = the middle of its bottom edge. Wrapped round '
                               'Informatization\'s body (four panels, .scale(0.7, 2, 1)), the false copy bursting, '
                               'Embodiment. .glow().unshaded().seeThrough()',
                               [('panel', [0, 0, 8], [16, 16, 8], ['north', 'south'])], img, frames, 2)


