def light_column(assets):
    """A column of light falling (two crossed planes), streaks running down it (4 frames)."""
    size, frames = 32, 4
    img = Image.new('RGBA', (size, size * frames), (0, 0, 0, 0))
    for f in range(frames):
        frame = Image.new('RGBA', (size, size), (0, 0, 0, 0))
        px = frame.load()
        for y in range(size):
            for x in range(size):
                d = abs((x + 0.5) / size - 0.5) * 2
                # bands of brightness travelling down the shaft (two per tile, a whole band per loop)
                band = 0.5 + 0.5 * math.sin((y - f * size / frames / 2) / size * math.tau * 2)
                rays = 0.75 + 0.25 * math.sin(x * 1.7)                             # faint lines along it
                a = max(0.0, 1 - d) ** 1.5 * (0.5 + 0.5 * band) * rays
                px[x, y] = (255, 255, 255, int(255 * min(1.0, a * 1.2)))
        img.paste(frame, (0, f * size))
    els = [('a', [0, 0, 8], [16, 16, 8], ['north', 'south']),
           ('b', [8, 0, 0], [8, 16, 16], ['east', 'west'])]
    return write_picture_model(assets, 'light_column',
                               'A column of light: two crossed planes of a soft shaft, brightest in the middle, '
                               'streaks running down it (animated), 1 block square. White: tint it (ice-clear for the '
                               'Scroll of Freezing, pale gold for a scroll read, orchid for Indoctrination). Pivot '
                               '8,0,8 = the middle of its bottom. Stretch it: .scale(width, height, width). '
                               '.glow().unshaded().seeThrough()', els, img, frames, 2)


