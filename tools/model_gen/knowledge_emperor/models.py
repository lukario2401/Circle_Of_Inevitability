def _blank(size):
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def _smooth(img, size):
    """Drawn at twice the size, brought down: soft edges."""
    return img.resize((size, size), Image.LANCZOS)


def _glyph(d, x, y, s, k, fill, width=1):
    """One of the Hermit's ancient symbols (k picks which): angular letters of an occult script."""
    k %= 9
    if k == 0:                                                              # an eye in a triangle
        d.polygon([(x, y - s), (x + s, y + s * 0.8), (x - s, y + s * 0.8)], outline=fill)
        d.ellipse([x - s * 0.35, y - s * 0.05, x + s * 0.35, y + s * 0.45], outline=fill)
    elif k == 1:                                                            # a key-like letter
        d.line([(x, y - s), (x, y + s)], fill=fill, width=width)
        d.line([(x, y - s * 0.3), (x + s * 0.7, y - s * 0.3)], fill=fill, width=width)
        d.line([(x, y + s * 0.3), (x + s * 0.5, y + s * 0.3)], fill=fill, width=width)
        d.ellipse([x - s * 0.4, y - s * 1.0, x + s * 0.4, y - s * 0.2], outline=fill)
    elif k == 2:                                                            # crossed hooks
        d.arc([x - s, y - s, x + s * 0.2, y + s * 0.2], 270, 90, fill=fill, width=width)
        d.arc([x - s * 0.2, y - s * 0.2, x + s, y + s], 90, 270, fill=fill, width=width)
    elif k == 3:                                                            # a star of three strokes
        for a in range(3):
            ang = math.pi * a / 3
            d.line([(x - math.cos(ang) * s, y - math.sin(ang) * s), (x + math.cos(ang) * s, y + math.sin(ang) * s)],
                   fill=fill, width=width)
    elif k == 4:                                                            # a square with a dot
        d.rectangle([x - s * 0.7, y - s * 0.7, x + s * 0.7, y + s * 0.7], outline=fill)
        d.ellipse([x - s * 0.2, y - s * 0.2, x + s * 0.2, y + s * 0.2], fill=fill)
    elif k == 5:                                                            # a crescent and a line
        d.arc([x - s, y - s, x + s, y + s], 40, 320, fill=fill, width=width)
        d.line([(x - s * 0.2, y), (x + s, y)], fill=fill, width=width)
    elif k == 6:                                                            # a trident
        d.line([(x, y - s * 0.4), (x, y + s)], fill=fill, width=width)
        d.line([(x - s * 0.8, y - s), (x - s * 0.8, y - s * 0.4), (x + s * 0.8, y - s * 0.4), (x + s * 0.8, y - s)],
               fill=fill, width=width)
        d.line([(x, y - s), (x, y - s * 0.4)], fill=fill, width=width)
    elif k == 7:                                                            # an hourglass letter
        d.line([(x - s * 0.8, y - s), (x + s * 0.8, y - s), (x - s * 0.8, y + s), (x + s * 0.8, y + s),
                (x - s * 0.8, y - s)], fill=fill, width=width)
    else:                                                                   # a circle crossed below
        d.ellipse([x - s * 0.6, y - s, x + s * 0.6, y + s * 0.2], outline=fill)
        d.line([(x, y + s * 0.2), (x, y + s)], fill=fill, width=width)
        d.line([(x - s * 0.5, y + s * 0.6), (x + s * 0.5, y + s * 0.6)], fill=fill, width=width)


def _glyph_ring(d, c, radius, count, fill, seed, s=4, width=1):
    rnd = random.Random(seed)
    for i in range(count):
        a = math.tau * (i + 0.5) / count
        _glyph(d, c + math.cos(a) * radius, c + math.sin(a) * radius, s, rnd.randrange(9), fill, width)


def _star_point(d, x, y, r, fill, points=4, inner=0.35):
    pts = []
    for i in range(points * 2):
        a = -math.pi / 2 + math.pi * i / points
        rr = r if i % 2 == 0 else r * inner
        pts.append((x + math.cos(a) * rr, y + math.sin(a) * rr))
    d.polygon(pts, fill=fill)


def _eye(d, cx, cy, w, h, opening, white, iris, pupil, lash, stars_in=None):
    """An almond eye 'opening' (0 = shut, 1 = wide). stars_in: colors for the stars in its iris."""
    if opening <= 0.05:
        d.arc([cx - w, cy - h * 0.5, cx + w, cy + h * 0.5], 0, 180, fill=lash, width=3)
        for i in range(5):                                                  # lashes
            x = cx - w * 0.6 + i * w * 0.3
            d.line([(x, cy + h * 0.45), (x - 2 + i, cy + h * 0.75)], fill=lash, width=2)
        return
    hh = h * opening
    top = [(cx - w, cy), (cx - w * 0.5, cy - hh), (cx, cy - hh * 1.12), (cx + w * 0.5, cy - hh), (cx + w, cy)]
    bot = [(cx + w, cy), (cx + w * 0.5, cy + hh * 0.8), (cx, cy + hh * 0.9), (cx - w * 0.5, cy + hh * 0.8)]
    d.polygon(top + bot, fill=white)
    r = min(h * 0.85, hh * 1.05)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=iris)
    if stars_in:
        rnd = random.Random(int(cx * 7 + cy * 13))
        for i in range(7):
            a, rr = rnd.random() * math.tau, rnd.random() * r * 0.8
            _star_point(d, cx + math.cos(a) * rr, cy + math.sin(a) * rr, 2.5 + rnd.random() * 2.5,
                        stars_in[i % len(stars_in)])
    pr = r * 0.32
    d.ellipse([cx - pr, cy - pr, cx + pr, cy + pr], fill=pupil)
    d.line(top, fill=lash, width=3)
    d.line(bot + [(cx - w, cy)], fill=lash, width=2)
    # the lids cut the iris: paint outside the almond clear
    return


def _clip_to_almond(img, cx, cy, w, h, opening):
    """Clears everything outside the eye's almond (so the iris does not spill past the lids)."""
    if opening <= 0.05:
        return img
    mask = Image.new('L', img.size, 0)
    md = ImageDraw.Draw(mask)
    hh = h * opening
    md.polygon([(cx - w, cy), (cx - w * 0.5, cy - hh), (cx, cy - hh * 1.12), (cx + w * 0.5, cy - hh), (cx + w, cy),
                (cx + w * 0.5, cy + hh * 0.8), (cx, cy + hh * 0.9), (cx - w * 0.5, cy + hh * 0.8)], fill=255)
    cut = Image.new('RGBA', img.size, (0, 0, 0, 0))
    cut.paste(img, (0, 0), mask)
    return cut


