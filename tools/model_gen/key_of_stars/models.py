"""Builds the Key Of Stars (Door pathway) ModelFx models (Java block-model JSON) and their textures.

Run from the repository root:
    python3 tools/model_gen/key_of_stars/models.py src/main/resources/assets/circle_of_inevitability
then press F3+T in game. ../hanged_man/render.py draws any of them to a PNG without the game:
    python3 tools/model_gen/hanged_man/render.py src/main/resources/assets/circle_of_inevitability out.png \
        key_of_stars/door_frame,key_of_stars/door_leaf key_of_stars/crystal_ball

Everything goes to models/model_fx/key_of_stars/ and textures/model_fx/key_of_stars/. Each JSON's "credit" says
what it is, how big, where its pivot is and how to play it; KeyOfStarsFx.java plays them all.

The model writer is the one of ../hand_of_order/models.py (same atlas layout, same rules, faces={...} for single
faces in another material), copied here so the Pathways can change without touching each other.

Rotations follow the right-hand rule, as in the other generators:
  axis x: +Y tilts toward +Z for a positive angle;  axis z: +Y tilts toward -X (so +X tilts toward +Y);
  axis y: +X turns toward -Z.
"""
import json
