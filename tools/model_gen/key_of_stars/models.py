def afterimage(assets):
    """An afterimage: the silhouette of a person in starlight, fading toward the feet, stars in it."""
    w, h = 64, 128
    img, d = _blank(w * 2, h * 2)
    cx = w
    body = Image.new('L', (w * 2, h * 2), 0)
    db = ImageDraw.Draw(body)
    db.ellipse([cx - 18, 8, cx + 18, 46], fill=255)                          # head
    db.polygon([(cx - 30, 54), (cx + 30, 54), (cx + 26, 150), (cx - 26, 150)], fill=255)   # body
    db.polygon([(cx - 30, 56), (cx - 44, 140), (cx - 34, 142), (cx - 22, 70)], fill=255)   # arms
    db.polygon([(cx + 30, 56), (cx + 44, 140), (cx + 34, 142), (cx + 22, 70)], fill=255)
    db.polygon([(cx - 24, 148), (cx - 4, 148), (cx - 6, 252), (cx - 22, 252)], fill=255)    # legs
    db.polygon([(cx + 4, 148), (cx + 24, 148), (cx + 22, 252), (cx + 6, 252)], fill=255)
    fill = Image.new('RGBA', (w * 2, h * 2), (0, 0, 0, 0))
    px = fill.load()
    for y in range(h * 2):
        a = int(200 * (1 - (y / (h * 2)) ** 1.8))
        for x in range(w * 2):
            px[x, y] = (255, 255, 255, a)
    img.paste(fill, (0, 0), body)
    edge = body.filter(ImageFilter.FIND_EDGES)
    img.paste(Image.new('RGBA', (w * 2, h * 2), (255, 255, 255, 255)), (0, 0), edge)
    dd = ImageDraw.Draw(img)
    rnd = random.Random(2)
    for _ in range(10):
        x, y = rnd.uniform(cx - 20, cx + 20), rnd.uniform(20, 200)
        if body.getpixel((int(x), int(y))):
            _star(dd, x, y, rnd.choice((4, 6)), (180, 200, 255, 255), 4, 0.3)
    img = _smooth(img, w, h)
    return write_picture_model(assets, 'afterimage',
                               'An afterimage: the silhouette of a person in starlight, fading toward the feet, a few '
                               'stars in it, 1 block wide and 2 tall, standing. White: tint it starlight. Pivot 8,0,8 '
                               '= the middle of its feet. Left behind by Blink and Escape Trick; Omnipresence\'s six '
                               'selves. Face it the way the Beyonder faced. .glow().unshaded().seeThrough()',
                               TALL, img)


