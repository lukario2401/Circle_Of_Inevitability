def _blank(w, h=None):
    img = Image.new('RGBA', (w, h or w), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def _smooth(img, w, h=None):
    return img.resize((w, h or w), Image.LANCZOS)


def _star(d, x, y, r, fill, points=4, inner=0.35, turn=0.0):
    """A pointed star: 'points' rays, the inner corners at 'inner' of the radius."""
    pts = []
    for i in range(points * 2):
        rr = r if i % 2 == 0 else r * inner
        a = -math.pi / 2 + turn + i * math.pi / points
        pts.append((x + math.cos(a) * rr, y + math.sin(a) * rr))
    d.polygon(pts, fill=fill)


def _door(d, x, y, w, h, fill, width=3, keyhole=True):
    """An arched door outline, its bottom middle at x, y."""
    d.line([(x - w / 2, y), (x - w / 2, y - h + w / 2)], fill=fill, width=width)
    d.line([(x + w / 2, y), (x + w / 2, y - h + w / 2)], fill=fill, width=width)
    d.arc([x - w / 2, y - h, x + w / 2, y - h + w], 180, 360, fill=fill, width=width)
    d.line([(x - w / 2 - width, y), (x + w / 2 + width, y)], fill=fill, width=width)
    if keyhole:
        _keyhole(d, x + w * 0.22, y - h * 0.42, max(2, w * 0.08), fill)


def _keyhole(d, x, y, s, fill):
    d.ellipse([x - s, y - s, x + s, y + s], fill=fill)
    d.polygon([(x - s * 0.6, y), (x + s * 0.6, y), (x + s, y + s * 2.6), (x - s, y + s * 2.6)], fill=fill)


def _star_field(d, size, count, seed, margin=0, radius=None, colors=(WHITE, SOFT)):
    rnd = random.Random(seed)
    c = size / 2
    placed = 0
    while placed < count:
        x, y = rnd.uniform(margin, size - margin), rnd.uniform(margin, size - margin)
        if radius is not None and math.hypot(x - c, y - c) > radius:
            continue
        r = rnd.choice((1.5, 2, 2.5, 3, 4, 6))
        col = colors[rnd.randrange(len(colors))]
        if r >= 4:
            _star(d, x, y, r * 1.6, col, 4, 0.3, rnd.uniform(0, 0.4))
        else:
            d.ellipse([x - r / 2, y - r / 2, x + r / 2, y + r / 2], fill=col)
        placed += 1


def _constellation(d, c, radius, count, seed, fill, line, width=2):
    """A few stars joined by thin lines, inside 'radius' of the middle."""
    rnd = random.Random(seed)
    pts = []
    for _ in range(count):
        a, r = rnd.uniform(0, math.tau), rnd.uniform(radius * 0.2, radius)
        pts.append((c + math.cos(a) * r, c + math.sin(a) * r))
    pts.sort(key=lambda p: math.atan2(p[1] - c, p[0] - c))
    for a, b in zip(pts, pts[1:]):
        if math.dist(a, b) < radius * 0.9:
            d.line([a, b], fill=line, width=width)
    for p in pts:
        _star(d, p[0], p[1], rnd.choice((5, 7, 9)), fill, 4, 0.3)


def _ring_of(d, c, radius, count, draw_one):
    for i in range(count):
        a = -math.pi / 2 + math.tau * i / count
        draw_one(c + math.cos(a) * radius, c + math.sin(a) * radius, a)


