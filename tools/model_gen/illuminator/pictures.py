def _lens_frame(d, c, r):
    d.ellipse([c - r - 10, c - r - 10, c + r + 10, c + r + 10], outline=(70, 150, 240, 120), width=4)
    d.ellipse([c - r, c - r, c + r, c + r], fill=(20, 50, 110, 150), outline=BLUEPRINT_LIGHT, width=8)
    ticks(d, c, r + 14, r + 24, 24, BLUEPRINT_LIGHT, 4, 6, 8)
    for a in (0.785, 2.356, 3.927, 5.498):                                 # four brackets of measurement
        x, y = c + math.cos(a) * (r + 30), c + math.sin(a) * (r + 30)
        d.arc([x - 14, y - 14, x + 14, y + 14], math.degrees(a) + 90, math.degrees(a) + 270, fill=BLUEPRINT, width=4)


def _weakness_symbol(d, c, kind):
    if kind == 'starlight':
        star_point(d, c, c, 62, STAR_GOLD, 4, 0.3)
        star_point(d, c, c, 40, (255, 255, 255, 255), 4, 0.3, math.pi / 4)
    elif kind == 'corrosion':
        d.polygon([(c, c - 64), (c + 40, c + 6), (c + 40, c + 20), (c, c + 58), (c - 40, c + 20), (c - 40, c + 6)],
                  fill=ACID)
        d.ellipse([c - 40, c - 18, c + 40, c + 58], fill=ACID)
        for x, y, r in ((c - 12, c + 12, 9), (c + 14, c - 6, 6), (c + 6, c + 30, 5)):
            d.ellipse([x - r, y - r, x + r, y + r], outline=(255, 255, 220, 255), width=3)
    elif kind == 'gravity':
        d.arc([c - 70, c + 20, c + 70, c + 150], 200, 340, fill=GRAVITY, width=8)
        for dx in (-30, 0, 30):
            d.line([(c + dx, c - 56), (c + dx, c + 18)], fill=GRAVITY, width=8)
            d.polygon([(c + dx - 14, c + 8), (c + dx + 14, c + 8), (c + dx, c + 32)], fill=GRAVITY)
    else:                                                                   # pierce: a bolt through cross hairs
        d.ellipse([c - 44, c - 44, c + 44, c + 44], outline=PIERCE, width=6)
        for a in range(4):
            ang = math.pi / 2 * a
            d.line([(c + math.cos(ang) * 22, c + math.sin(ang) * 22), (c + math.cos(ang) * 64, c + math.sin(ang) * 64)],
                   fill=PIERCE, width=6)
        d.line([(c - 60, c + 60), (c + 46, c - 46)], fill=RED, width=8)
        d.polygon([(c + 60, c - 60), (c + 30, c - 52), (c + 52, c - 30)], fill=RED)


def appraisal_marks(assets):
    out = []
    labels = {'starlight': 'starlight (undead, spirits, summoned things): a white-gold star',
              'corrosion': 'corrosion (the armored, constructs): a drop of bubbling acid',
              'gravity': 'gravity (the flying, the fast): arrows pressing down onto an arc of ground',
              'pierce': 'pierce (everything else, players): a red bolt through cross hairs'}
    for kind, label in labels.items():
        size = 128
        big = size * 2
        img, d = blank(big)
        c = big / 2
        _lens_frame(d, c, 84)
        _weakness_symbol(d, c, kind)
        out.append(write_picture_model(
            assets, f'appraisal_{kind}',
            f'The Appraised mark, weak to {label}: a lens of blueprint blue with measuring ticks and brackets, the '
            'weakness inside it. Its own colors. 1 block, standing (it faces north and south). Pivot 8,8,8 = its '
            'middle. Over the Appraised head (modelOn, .spin(2f)) for as long as the mark lasts. '
            '.glow().unshaded().seeThrough()', STANDING, smooth(img, size)))
    return out


def flaw_mark(assets):
    size = 128
    big = size * 2
    img, d = blank(big)
    c = big / 2
    rnd = random.Random(12)
    x, y = c - 90, c + 70
    pts = [(x, y)]
    for _ in range(9):                                                     # the hairline crack
        x += rnd.uniform(14, 24)
        y -= rnd.uniform(10, 22)
        pts.append((x, y))
    d.line(pts, fill=WHITE, width=5)
    for p in pts[2::3]:
        a = rnd.random() * math.tau
        d.line([p, (p[0] + math.cos(a) * 26, p[1] + math.sin(a) * 26)], fill=SOFT, width=3)
    for a, b in ((pts[1], pts[4]), (pts[5], pts[8])):                       # brackets measuring it
        d.line([(a[0] - 10, a[1] - 18), (b[0] - 10, b[1] - 18)], fill=SOFT, width=3)
        for p in (a, b):
            d.line([(p[0] - 10, p[1] - 26), (p[0] - 10, p[1] - 10)], fill=SOFT, width=3)
    d.ellipse([c - 8, c - 8, c + 8, c + 8], fill=WHITE)
    for a in range(4):
        ang = math.pi / 4 + math.pi / 2 * a
        d.line([(c + math.cos(ang) * 20, c + math.sin(ang) * 20), (c + math.cos(ang) * 44, c + math.sin(ang) * 44)],
               fill=WHITE, width=4)
    return write_picture_model(assets, 'flaw_mark',
                               'Exploit Flaw: a hairline crack found and measured, brackets along it, a point of light '
                               'where it gives; 1 block, standing (it faces north and south). White: tint it blueprint '
                               'blue. Pivot 8,8,8 = its middle. Flashed on the body where the flaw is struck. '
                               '.glow().unshaded().seeThrough()', STANDING, smooth(img, size))


