"""The Illuminator's picture models: models whose faces each show one whole picture (a mark over a head, a circle on
the ground, a mural, a beam, the sky of Mechanical Heaven). Run by models.py; on its own:
    python3 tools/model_gen/illuminator/pictures.py src/main/resources/assets/circle_of_inevitability

White pictures take any tint with .color(...); the ones that keep their own colors say so in their credit.
Each picture is drawn at twice its size and brought down, for soft edges.
"""
