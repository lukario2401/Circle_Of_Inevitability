def _mural(kind):
    w = 128
    big = w * 2
    img, d = blank(big)
    rnd = random.Random({'ancient': 1, 'sea': 2, 'cathedral': 3, 'industry': 4}[kind])
    x0, x1, y0, y1 = 30, 226, 24, 232
    for y in range(y0, y1):                                                # the painted cloth
        for x in range(x0, x1, 2):
            t = rnd.random() * 0.15 + 0.85
            col = tuple(int(v * t) for v in (236, 220, 180)) + (255,)
            d.line([(x, y), (x + 1, y)], fill=col)
    ink = (60, 46, 30, 255)
    paint = {'ancient': ((232, 170, 70, 255), (200, 120, 50, 255), (90, 130, 190, 255)),
             'sea': ((60, 110, 170, 255), (240, 240, 250, 255), (120, 80, 40, 255)),
             'cathedral': ((150, 60, 70, 255), (90, 110, 160, 255), (230, 200, 120, 255)),
             'industry': ((110, 100, 96, 255), (217, 164, 65, 255), (230, 230, 230, 255))}[kind]
    a, b, sky = paint
    horizon = 170
    if kind == 'ancient':                                                  # pyramids under a great sun
        d.ellipse([140, 46, 196, 102], fill=a, outline=ink, width=3)
        for k in range(12):
            ang = math.tau * k / 12
            d.line([(168 + math.cos(ang) * 32, 74 + math.sin(ang) * 32), (168 + math.cos(ang) * 44, 74 + math.sin(ang) * 44)],
                   fill=a, width=4)
        d.polygon([(46, horizon), (104, 84), (162, horizon)], fill=b, outline=ink)
        d.polygon([(130, horizon), (172, 112), (214, horizon)], fill=(220, 150, 80, 255), outline=ink)
        d.line([(104, 84), (104, horizon)], fill=ink, width=2)
        d.rectangle([x0, horizon, x1, y1 - 10], fill=(214, 180, 110, 255))
        for k in range(6):
            fx = 56 + k * 26
            d.line([(fx, 200), (fx, 222)], fill=ink, width=4)
            d.ellipse([fx - 5, 188, fx + 5, 198], fill=ink)
    elif kind == 'sea':                                                    # a tall ship on the waves
        d.rectangle([x0, horizon, x1, y1 - 10], fill=a)
        for k in range(7):
            y = horizon + 10 + k * 8
            for xx in range(x0 + (k % 2) * 10, x1, 22):
                d.arc([xx, y - 6, xx + 20, y + 6], 180, 360, fill=b, width=3)
        d.polygon([(70, 150), (190, 150), (170, 176), (90, 176)], fill=sky, outline=ink)                        # the hull
        for mx in (100, 130, 160):
            d.line([(mx, 150), (mx, 60)], fill=ink, width=4)
            d.polygon([(mx - 22, 72), (mx + 22, 72), (mx + 18, 112), (mx - 18, 112)], fill=b, outline=ink)
        d.polygon([(160, 60), (190, 66), (160, 72)], fill=(200, 60, 60, 255))
    elif kind == 'cathedral':                                              # a cathedral with a rose window
        d.rectangle([x0, horizon + 20, x1, y1 - 10], fill=(140, 150, 120, 255))
        d.polygon([(72, 200), (72, 100), (128, 50), (184, 100), (184, 200)], fill=(200, 196, 186, 255), outline=ink)
        d.polygon([(54, 200), (54, 70), (72, 40), (90, 70), (90, 200)], fill=(190, 186, 176, 255), outline=ink)
        d.polygon([(166, 200), (166, 70), (184, 40), (202, 70), (202, 200)], fill=(190, 186, 176, 255), outline=ink)
        d.ellipse([106, 92, 150, 136], fill=a, outline=ink, width=3)
        for k in range(8):
            ang = math.tau * k / 8
            d.line([(128, 114), (128 + math.cos(ang) * 20, 114 + math.sin(ang) * 20)], fill=sky, width=3)
        d.polygon([(114, 200), (114, 160), (128, 146), (142, 160), (142, 200)], fill=b, outline=ink)
        d.line([(128, 50), (128, 28)], fill=ink, width=3)
        d.line([(120, 36), (136, 36)], fill=ink, width=3)
    else:                                                                  # a steam engine and its gears
        d.rectangle([x0, horizon + 20, x1, y1 - 10], fill=(120, 110, 100, 255))
        d.rectangle([60, 120, 170, 176], fill=a, outline=ink, width=3)
        d.ellipse([150, 112, 210, 172], fill=b, outline=ink, width=3)
        for k in range(8):
            ang = math.tau * k / 8
            d.line([(180, 142), (180 + math.cos(ang) * 28, 142 + math.sin(ang) * 28)], fill=ink, width=3)
        d.rectangle([80, 70, 100, 120], fill=a, outline=ink, width=2)
        for sx, sy, r in ((90, 60, 12), (104, 44, 16), (122, 30, 20)):
            d.ellipse([sx - r, sy - r, sx + r, sy + r], fill=sky)
        gear_shape(d, 64, 196, 22, 10, b, ink)
        gear_shape(d, 100, 204, 14, 8, b, ink, 0.3)
        d.rectangle([40, 176, 216, 182], fill=ink)
    d.rectangle([x0, y0, x1, y1], outline=ink, width=3)
    for yy in (y0 - 12, y1):                                               # the brass rods it hangs from
        d.rounded_rectangle([x0 - 14, yy, x1 + 14, yy + 12], 6, fill=BRASS, outline=BRASS_DARK, width=3)
        d.ellipse([x0 - 24, yy - 2, x0 - 8, yy + 14], fill=BRASS_LIGHT, outline=BRASS_DARK, width=2)
        d.ellipse([x1 + 8, yy - 2, x1 + 24, yy + 14], fill=BRASS_LIGHT, outline=BRASS_DARK, width=2)
    return smooth(img, w)


