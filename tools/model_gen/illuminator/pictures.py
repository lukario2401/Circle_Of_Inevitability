def save_json(assets, name, data):
    path = os.path.join(assets, 'models/model_fx', name + '.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)


def write_picture_model(assets, name, credit, elements, img, frames=1, frametime=3, tex_name=None):
    """A model whose every face shows the whole of one picture. frames > 1: img holds the frames stacked downward
    (an animated texture). tex_name: the picture's file name when it differs from the model's."""
    tex_name = tex_name or name
    tex_path = os.path.join(assets, 'textures/model_fx', FOLDER, tex_name + '.png')
    os.makedirs(os.path.dirname(tex_path), exist_ok=True)
    img.save(tex_path)
    meta = tex_path + '.mcmeta'
    if frames > 1:
        with open(meta, 'w') as f:
            json.dump({'animation': {'frametime': frametime, 'interpolate': True}}, f)
    elif os.path.exists(meta):
        os.remove(meta)
    tex_id = f'{NAMESPACE}:model_fx/{FOLDER}/{tex_name}'
    els = []
    for el in elements:
        el_name, frm, to, faces = el[:4]
        out = {'name': el_name, 'from': [round(v, 4) for v in frm], 'to': [round(v, 4) for v in to], 'shade': False}
        if len(el) > 4 and el[4] is not None and el[4][1] != 0.0:
            axis, angle, origin = el[4]
            if angle not in ALLOWED:
                raise ValueError(f'{name}/{el_name}: angle {angle}')
            out['rotation'] = {'angle': angle, 'axis': axis, 'origin': [round(v, 4) for v in origin]}
        out['faces'] = {face: {'uv': [0, 0, 16, 16], 'texture': '#0'} for face in faces}
        els.append(out)
    w = img.size[0]
    save_json(assets, FOLDER + '/' + name, {
        'credit': CREDIT + credit + MADE_BY,
        'texture_size': [w, w], 'textures': {'0': tex_id, 'particle': tex_id}, 'elements': els})
    return FOLDER + '/' + name


def blank(size):
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img)


def smooth(img, size):
    return img.resize((size, size), Image.LANCZOS)


def animated(frames_list, size):
    img = Image.new('RGBA', (size, size * len(frames_list)), (0, 0, 0, 0))
    for i, f in enumerate(frames_list):
        img.paste(f, (0, i * size))
    return img


def star_point(d, x, y, r, fill, points=4, inner=0.38, turn=0.0):
    pts = []
    for i in range(points * 2):
        a = -math.pi / 2 + turn + math.pi * i / points
        rr = r if i % 2 == 0 else r * inner
        pts.append((x + math.cos(a) * rr, y + math.sin(a) * rr))
    d.polygon(pts, fill=fill)


def ticks(d, c, r0, r1, count, fill, width=2, every=0, long=0):
    for i in range(count):
        a = math.tau * i / count
        rr0 = r0 - (long if every and i % every == 0 else 0)
        d.line([(c + math.cos(a) * rr0, c + math.sin(a) * rr0), (c + math.cos(a) * r1, c + math.sin(a) * r1)],
               fill=fill, width=width)


def gear_shape(d, cx, cy, r, teeth, fill, hole=None, turn=0.0, tooth=0.18, spokes=0, spoke_fill=None, inner=None):
    """A gear: 'teeth' teeth round radius r, a hole in the middle; spokes cut out of the web if asked."""
    pts = []
    for i in range(teeth * 4):
        a = turn + math.tau * i / (teeth * 4)
        rr = r if (i % 4) in (1, 2) else r * (1 - tooth)
        pts.append((cx + math.cos(a) * rr, cy + math.sin(a) * rr))
    d.polygon(pts, fill=fill)
    if spokes and inner is not None:
        ri = r * 0.68
        d.ellipse([cx - ri, cy - ri, cx + ri, cy + ri], fill=inner)
        for k in range(spokes):
            a = turn + math.tau * k / spokes
            d.line([(cx, cy), (cx + math.cos(a) * ri, cy + math.sin(a) * ri)], fill=spoke_fill or fill,
                   width=max(2, int(r * 0.16)))
        rh = r * 0.22
        d.ellipse([cx - rh, cy - rh, cx + rh, cy + rh], fill=spoke_fill or fill)
    if hole is not None:
        rh = r * 0.09
        d.ellipse([cx - rh, cy - rh, cx + rh, cy + rh], fill=hole)


def scribble_math(d, x, y, s, k, fill, width=2):
    """One small piece of mathematics (k picks which): integral, sum, root, fraction, equals, pi, delta, arrow."""
    k %= 8
    if k == 0:
        d.arc([x - s * 0.2, y - s, x + s * 0.4, y - s * 0.4], 180, 360, fill=fill, width=width)
        d.line([(x + s * 0.1, y - s * 0.7), (x - s * 0.1, y + s * 0.7)], fill=fill, width=width)
        d.arc([x - s * 0.6, y + s * 0.4, x, y + s], 0, 180, fill=fill, width=width)
    elif k == 1:
        d.line([(x + s * 0.6, y - s), (x - s * 0.6, y - s), (x, y), (x - s * 0.6, y + s), (x + s * 0.6, y + s)],
               fill=fill, width=width)
    elif k == 2:
        d.line([(x - s, y), (x - s * 0.6, y + s * 0.2), (x - s * 0.2, y + s), (x + s * 0.1, y - s), (x + s, y - s)],
               fill=fill, width=width)
    elif k == 3:
        d.line([(x - s * 0.8, y), (x + s * 0.8, y)], fill=fill, width=width)
        d.ellipse([x - s * 0.2, y - s * 0.8, x + s * 0.2, y - s * 0.4], outline=fill, width=width)
        d.ellipse([x - s * 0.2, y + s * 0.4, x + s * 0.2, y + s * 0.8], outline=fill, width=width)
    elif k == 4:
        d.line([(x - s * 0.8, y - s * 0.3), (x + s * 0.8, y - s * 0.3)], fill=fill, width=width)
        d.line([(x - s * 0.8, y + s * 0.3), (x + s * 0.8, y + s * 0.3)], fill=fill, width=width)
    elif k == 5:
        d.line([(x - s * 0.8, y - s * 0.6), (x + s * 0.8, y - s * 0.6)], fill=fill, width=width)
        d.line([(x - s * 0.4, y - s * 0.6), (x - s * 0.5, y + s * 0.8)], fill=fill, width=width)
        d.line([(x + s * 0.4, y - s * 0.6), (x + s * 0.5, y + s * 0.8)], fill=fill, width=width)
    elif k == 6:
        d.polygon([(x, y - s), (x + s * 0.9, y + s * 0.8), (x - s * 0.9, y + s * 0.8)], outline=fill)
        d.line([(x, y - s), (x + s * 0.9, y + s * 0.8), (x - s * 0.9, y + s * 0.8), (x, y - s)], fill=fill, width=width)
    else:
        d.line([(x - s, y), (x + s, y)], fill=fill, width=width)
        d.line([(x + s * 0.5, y - s * 0.5), (x + s, y), (x + s * 0.5, y + s * 0.5)], fill=fill, width=width)


def math_ring(d, c, radius, count, fill, seed, s=8, width=2):
    rnd = random.Random(seed)
    for i in range(count):
        a = math.tau * (i + 0.5) / count
        scribble_math(d, c + math.cos(a) * radius, c + math.sin(a) * radius, s, rnd.randrange(8), fill, width)


