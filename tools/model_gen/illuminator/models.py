BOOK_MATS = ['book_cover', 'page_edges', 'book_page', 'brass']


def _illusory_book(step):
    m = Model(f'illusory_book_{step}',
              f'Illusory Book, step {step} of 3 (0 = shut, standing on its spine, 1 = falling open, 2 = wide open, '
              'its pages up): a great book bound in ink blue-black leather with brass corners and a lamp-and-gear '
              'sigil, 1 block across open. Its spine runs north-south. Pivot 8,0,8 = the bottom of the spine. '
              'ModelFx.of("illuminator/illusory_book").frames(3).smooth(); .scale(2f) and more for the book that '
              'swallows enemies. .glow()',
              BOOK_MATS)
    for side, sign in (('w', -1), ('e', 1)):
        if step == 0:                                                       # shut: two upright halves
            if sign < 0:
                cov = ([6.4, 0.4, 1.0], [7.2, 14.4, 15.0])
                pag = ([7.2, 0.8, 1.6], [8.0, 13.8, 14.4])
            else:
                cov = ([8.8, 0.4, 1.0], [9.6, 14.4, 15.0])
                pag = ([8.0, 0.8, 1.6], [8.8, 13.8, 14.4])
            rot = ('z', 0.0, [8, 0, 8])
            top = 'east' if sign < 0 else 'west'
        elif step == 1:                                                     # the same halves, 45 degrees out
            cov, pag = ((([6.4, 0.4, 1.0], [7.2, 14.4, 15.0]), ([7.2, 0.8, 1.6], [8.0, 13.8, 14.4])) if sign < 0
                        else (([8.8, 0.4, 1.0], [9.6, 14.4, 15.0]), ([8.0, 0.8, 1.6], [8.8, 13.8, 14.4])))
            rot = ('z', 45.0 if sign < 0 else -45.0, [8, 0, 8])
            top = 'east' if sign < 0 else 'west'
        else:                                                               # wide open: halves lying out, a shallow V
            if sign < 0:
                cov = ([1.0, -0.8, 1.0], [8.0, 0.0, 15.0])
                pag = ([1.6, 0.0, 1.6], [8.0, 0.8, 14.4])
